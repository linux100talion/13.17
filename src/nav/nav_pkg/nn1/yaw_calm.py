#!/usr/bin/env python3
"""YawCalm — «курс СЕЙЧАС спокоен»: не крутимся дольше `still` секунд подряд.

Зачем. Угол рамы (`FrameAnchor.latch_yaw`) защёлкивается по ОДНОЙ мгновенной паре
«курс AHRS / курс VINS». Потоки приходят разными трактами с разной задержкой, поэтому
на вираже их разность = ω·лаг, а НЕ поворот кадра. Схватил в размахе — заморозил
чужие градусы в раме навсегда (с 2026-09-10 жёсткая подтяжка угол больше не правит,
так что исправить его нечем).

Замер 2026-09-10, Δyaw якоря против истинного поворота кадра на открытии моста:

    203257 (пилот, латч на курсе 90°)   +6.0° против +0.4°  → ошибка 5.6°, дрейф 0.08 м
    202510 (пилот)                      -2.7° против +1.2°  → 3.9°,        дрейф 0.81 м
    yawab_check5 (реплей, рыскал)      +29.5° против +0.1°  → 29.4°,       EKF ушёл на 1959 м

⚠️ Мешает НЕ РАЗВЁРНУТОСТЬ, а ВРАЩЕНИЕ в момент захвата: полёт 203257 латчился на
курсе 90° от взлётного и дал лучший результат дня. Пилот рыскает нарочно (так VINS
быстрее наблюдает курс) — и попадает захватом в паузу между взмахами. Реплей рыскал
непрерывно и попал в размах.

Судим по УГЛУ ЗА ИНТЕРВАЛ, а не по мгновенной производной: тот же приём, что у
`_AltSettled` (см. серию IG1s — дифференциатор со своим шумом дребезжал и держал ось
закрытой весь полёт). Здесь дифференциатора нет: есть накопленное «спокойное» время,
которое обнуляется, как только курс уехал больше чем на `wz_max * dt`.
"""
import math


def _wrap(a):
    return (a + math.pi) % (2.0 * math.pi) - math.pi


class YawCalm:
    """Курс спокоен = |ω| ниже `wz_max` (°/с) непрерывно дольше `still` секунд."""

    def __init__(self, wz_max: float = 15.0, still: float = 0.5):
        self.wz_max = float(wz_max)
        self.still = float(still)
        self.wz = 0.0               # последняя оценка |ω|, °/с (для лога)
        self._prev = None           # (t, yaw)
        self._quiet = 0.0

    def reset(self) -> None:
        self._prev = None
        self._quiet = 0.0
        self.wz = 0.0

    def update(self, t, yaw) -> bool:
        """→ True, если курс спокоен. Первый отсчёт — всегда False (судить не по чему)."""
        t = float(t)
        prev, self._prev = self._prev, (t, float(yaw))
        if prev is None or t <= prev[0]:
            self._quiet = 0.0
            return False
        dt = t - prev[0]
        self.wz = abs(math.degrees(_wrap(float(yaw) - prev[1]))) / dt
        if self.wz > self.wz_max:
            self._quiet = 0.0
            return False
        self._quiet += dt
        return self._quiet >= self.still
