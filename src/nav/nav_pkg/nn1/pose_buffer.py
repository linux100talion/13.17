#!/usr/bin/env python3
"""PoseBuffer — ШТАМПОВАННЫЕ ПОЗЫ EKF → поза НА МОМЕНТ КАДРА VINS.

Зачем. `FrameAnchor` спаривает две позы — свою (VINS) и полётника (EKF) — и по этой
паре считает раму. До 2026-09-09 пара бралась ПО ПРИХОДУ: последняя поза EKF против
последней одометрии VINS. Но VINS считается на кадре и приходит позже, и разброс этой
задержки в полёте (замер 181233/181936, после снятия расхождения ТЕМПА sim/wall —
там набегает 1.5 % и легко выдаёт себя за задержку) — медиана 0.14–0.15 с, 90 %
0.20–0.22 с, хвост до 0.33 с. На крейсере 3–5 м/с это 0.45–0.75 м мнимого расхода,
причём знак не случайный: лаг больше на быстром ходу, и якорь систематически тянет
назад по курсу. Тот же лаг съедал большую часть порога жёсткой подтяжки (1 м) — то
есть подтяжки будились лагом, а не расхождением рам. В худшем случае (полёт 173415,
подвис VINS на 1.96 с при развороте 10 °/с) в раму защёлкивались 20° угла.

Лечение — то же, что у углов канала вида сверху: не «последнее пришедшее», а
ИНТЕРПОЛЯЦИЯ МЕЖДУ ДВУМЯ СОСЕДНИМИ ОТСЧЁТАМИ на момент штампа кадра. Родня и образец
стиля — `control_pkg/perception/attitude_buffer.py`.

⚠️ И ЗАМЕР СКАЗАЛ «ПОКА НЕТ» (`src/lab/anchor_replay.py`, 2026-09-09, три прогона).
Спаривание по штампу вышло ХУЖЕ спаривания по приходу: медианный расход якоря
0.083 → 0.107 и 0.114 → 0.264 м, подтяжек 1 → 3. Причина не в буфере: поза EKF —
НЕ независимый наблюдатель того же момента, а ОТКЛИК на нашу же публикацию.
`vision_pose` уходит в полётник со штампом `time.time()` («сейчас»), хотя описывает
борт на 0.15 с раньше, — значит EKF уже сдвинут ровно на тот же лаг, и пара «по
приходу» с ним СОГЛАСОВАНА, а «по штампу» рассогласована. Поэтому
`anchor_pair_by_stamp` по умолчанию ВЫКЛЮЧЕН: класс это не решает, а вредит.
Включать — вместе с честным штампом `vision_pose` (лаг тогда компенсирует сам
AP_VisualOdom своим параметром задержки) и обязательно перемерив тем же стендом.
Сам разъезд пары при этом реален и никуда не делся: медиана 0.16 м, хвост до 0.45 м.

Списки кортежей, не numpy: кладём по одному отсчёту, спрашиваем один момент —
векторизовать нечего. numpy остаётся там, где он и был, — в арифметике якоря.
"""
import math


def _wrap(a):
    return (a + math.pi) % (2.0 * math.pi) - math.pi


class PoseBuffer:
    """Кольцо поз (t, x, y, z, yaw) глубиной keep_sec, выборка на момент t."""

    def __init__(self, keep_sec: float = 3.0):
        self.buf = []                       # (t, x, y, z, yaw), по времени
        self.keep = float(keep_sec)

    def push(self, t, x, y, z, yaw) -> None:
        t = float(t)
        # штамп прыгнул назад (перезапуск часов / смена источника времени) — кольцо
        # уже не про этот полёт, начинаем заново, иначе двоичный поиск врёт
        if self.buf and t < self.buf[-1][0]:
            self.buf = []
        self.buf.append((t, float(x), float(y), float(z), float(yaw)))
        while self.buf and t - self.buf[0][0] > self.keep:
            self.buf.pop(0)

    def newest(self):
        return self.buf[-1][0] if self.buf else None

    def oldest(self):
        return self.buf[0][0] if self.buf else None

    def ready(self, t) -> bool:
        """Есть чем ИНТЕРПОЛИРОВАТЬ на момент t (t накрыт отсчётами)?"""
        return bool(self.buf) and self.buf[0][0] <= t <= self.buf[-1][0]

    def at(self, t):
        """(x, y, z, yaw) на момент t линейной интерполяцией; None — буфер пуст.
        За краями — удержание крайнего отсчёта (поведение «как было»)."""
        b = self.buf
        if not b:
            return None
        if t <= b[0][0]:
            return b[0][1], b[0][2], b[0][3], b[0][4]
        if t >= b[-1][0]:
            return b[-1][1], b[-1][2], b[-1][3], b[-1][4]
        lo, hi = 0, len(b) - 1
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if b[mid][0] <= t:
                lo = mid
            else:
                hi = mid
        a, c = b[lo], b[hi]
        dt = c[0] - a[0]
        k = 0.0 if dt <= 0 else (t - a[0]) / dt
        # курс — через обёртку: между +179° и −179° один градус, а не 358
        return (a[1] + k * (c[1] - a[1]),
                a[2] + k * (c[2] - a[2]),
                a[3] + k * (c[3] - a[3]),
                a[4] + k * _wrap(c[4] - a[4]))
