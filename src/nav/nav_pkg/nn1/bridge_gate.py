# bridge_gate.py — ГЕЙТ ЗДОРОВЬЯ МОСТА VINS→EKF (ray_tracer). Чистая логика без
# ROS — тестируется офлайн (src/nav/test/test_bridge_gate.py).
#
# ЗАЧЕМ (полёт lv2_joy_20260906_142811, cmd/6): VINS разнёсся сразу после init на
# висении (|v| 1.3 → 49 м/с за 18 с, 111 скачков позы), а мост ray_tracer, не зная
# о здоровье, 687 раз «подтянул» якорь кадра (расход > 1 м на каждой одометрии) и
# на каждой одометрии публиковал /mavros/vision_pose/pose = позиция EKF в момент
# подтяжки + мусорный прирост, ориентация VINS повёрнутая на Δyaw до +19°. EKF3
# отравился: ориентация AHRS против истины ушла на 6–12° по крену/тангажу и
# 20–33° по курсу, и НЕ вернулась после выздоровления VINS (якорь остался с Δyaw
# +18°, свежего латча не было). На кривой ориентации не работает ничего: канал
# IPM считает дерото по ней (продольная ось ослепла), ALT_HOLD держит ложный
# горизонт (авторитет демпфера 150 PWM ≈ 9–13° съеден ошибкой целиком) — DpHold
# унесло на 8 м/с. Гейт здоровья лётной ноды (handover.vins_sane) защищал только
# ЯРУС; мост кормил полётник без всякой проверки.
#
# ЧТО ДЕЛАЕТ. Мост ЗАКРЫТ (vision_pose не публикуется, якорь заморожен), если:
#   - |twist| > v_max (12 м/с — потолок гейта здоровья ноды, честный борт столько
#     не летает);
#   - ПЕРЕРОЖДЕНИЕ потока: дыра штампов > gap_sec или скачок позы быстрее v_jump
#     между соседними одометриями (детект VinsTrack лётной ноды, 1:1) — новая
#     рама → якорь надо латчить ЗАНОВО (relatch_pending), не подтягивать;
#   - ШТОРМ ПОДТЯЖЕК: ≥ relatch_n жёстких подтяжек за relatch_win с — расход
#     > relatch_m на каждой одометрии бывает только у разноса (норма: 0–2 за
#     полёт); рама после шторма — мусор → латч заново;
#   - внешний вердикт лётной ноды (/vins/sane = False) — когда нода есть и её
#     сообщение свежее; на Orin без ноды мост живёт только своими проверками;
#   - НЕЗРЕЛОСТЬ (/vins/bridge_ok = False, с 2026-09-09): VINS ещё не доказал
#     себя (odom < vins_min или здоровье короче rth_ripe_sec) — позу в EKF не
#     пускаем ВООБЩЕ. Полёт 073004: 2-4 с мусора незрелого VINS накренили AHRS,
#     и EKF уехал на 200 м уже при закрытом мосте; «возврат» сел в 52 м от старта.
# Закрытие держится hold_sec после последней причины (латч гейта); открытие —
# только при здоровом потоке. НА ПЕРВОМ ОТКРЫТИИ за полёт гейт просит якорь не
# латчиться (take_open_reset): за время закрытия EKF уехал, и латч к его позе
# означал бы «подтверждаю твой дрейф» — вместо этого отдаём сырой VINS, и
# полётник пересаживается на свежую раму (разбор 114844 vs 120819). Счётчики closes/rebirths — в /nn1/bridge и
# статус (brg=/brw=/brl=/brc=).
#
# ⚠️ ШТОРМ ПОДТЯЖЕК — сигнал СМЕШАННЫЙ (полёт 173102, 2026-09-06): подтяжка
# = расход map(VINS) − EKF, а EKF в GPS-denied без aiding (мост закрыт) сам
# уезжает — на открытии свежий латч к убежавшему EKF, подтяжка каждые 0.1 с,
# vision = позиция убежавшего EKF, инновации нет, EKF не ресетится, через 0.3 с
# снова «шторм» → дедлок (15 закрытий за 2 мин, LOITER на 20 м не брался).
# Плюс 3D-норма расхода считала z: VINS z на быстром наборе отстаёт ~1 м →
# ложный шторм на самом наборе. Лечение — в FrameAnchor: расход только xy и
# грейс grace_sec после (пере)латча (якорь стоит, EKF ресетится к vision);
# шторм здесь остаётся как страховка от медленного разноса (< v_max, без
# скачков) — с грейсом он набирается только за ≥ 3·grace_sec.
# ============================================================================
import math


class BridgeGate:
    def __init__(self, v_max=12.0, v_jump=12.0, gap_sec=1.0, relatch_n=3,
                 relatch_win=5.0, hold_sec=5.0, open_reset=True):
        self.v_max = float(v_max)
        self.v_jump = float(v_jump)
        self.gap_sec = float(gap_sec)
        self.relatch_n = int(relatch_n)
        self.relatch_win = float(relatch_win)
        self.hold_sec = float(hold_sec)
        # состояние
        self._prev = None               # (t, x, y) предыдущей одометрии
        self._closed_until = -math.inf  # мост закрыт до этого времени
        self._relatch_ts = []           # штампы подтяжек в окне
        self.reason = '-'               # причина последнего закрытия
        self.closes = 0                 # закрытий за полёт
        self.rebirths = 0               # перерождений потока
        self.relatch_pending = False    # якорь надо латчить заново
        # ПЕРВОЕ ОТКРЫТИЕ МОСТА В ПОЛЁТЕ — не усыновлять уехавший EKF (см. ниже)
        self.open_reset = bool(open_reset)
        self._was_open = None           # прошлое состояние (детект фронта)
        self._open_reset_pending = False
        self._first_open_done = False

    # --- события ------------------------------------------------------------
    def on_odom(self, t, x, y, speed, ext_sane=None, ready=None) -> bool:
        """Одометрия VINS: t — штамп (с), x/y — поза, speed — |twist_xy| (м/с),
        ext_sane — свежий вердикт лётной ноды (None = ноды нет/протух),
        ready — ГЕЙТ ЗРЕЛОСТИ: False = VINS ещё не доказал себя (не зрел / не
        здоров ripe_sec подряд), позу в EKF не пускаем вовсе; None = ноды нет.
        Возвращает: мост ОТКРЫТ."""
        reborn = False
        if self._prev is not None:
            pt, px, py = self._prev
            dt = t - pt
            if dt > 0.0:
                if dt > self.gap_sec or math.hypot(x - px, y - py) / dt > self.v_jump:
                    reborn = True
        self._prev = (t, x, y)
        if reborn:
            self.rebirths += 1
            self.relatch_pending = True
            self._close(t, 'reborn')
        if speed > self.v_max:
            self._close(t, f'v{speed:.0f}')
        if ext_sane is False:
            self._close(t, 'ext')
        if ready is False:
            # ЗРЕЛОСТЬ (2026-09-09): пока VINS не доказал себя, полётник не
            # получает от него НИ ОДНОЙ позы. Полёт 073004: мост кормил EKF
            # первые 2-4 с разноса после отрыва — этого хватило, чтобы AHRS
            # накренился, а EKF уехал на 200 м уже при закрытом мосте.
            self._close(t, 'ripe')
        # ФРОНТ «закрыт → открыт», ПЕРВЫЙ за полёт: пока мост был закрыт (обычно
        # гейтом зрелости после отрыва), EKF без позиционной подтяжки уезжал —
        # 17 м за 22 с в полёте 114844. Если в этот момент якорь залатчится к его
        # текущей позе, мы СВОЕЙ РУКОЙ подтвердим дрейф: vision_pose совпадёт с
        # тем, что полётник и так думает, и он останется в уехавшей раме на весь
        # полёт. Если же якоря нет (тождественный), уходит СЫРОЙ VINS, полётник
        # видит расхождение и СБРАСЫВАЕТ позицию на нашу свежую раму — дрейф
        # схлопывается (114844: 16.2 м остались; 120819, где EKF успел сдаться
        # сам и якорь латчиться было не к чему: 2.25 м). Раньше это решала
        # случайность (успел ли EKF объявить позицию потерянной) — теперь решаем мы.
        open_now = self.is_open(t)
        if (self.open_reset and self._was_open is False and open_now
                and not self._first_open_done):
            self._first_open_done = True
            self._open_reset_pending = True
        self._was_open = open_now
        return open_now

    def on_relatch(self, t) -> bool:
        """Жёсткая подтяжка якоря. Возвращает: мост ЗАКРЫЛСЯ штормом подтяжек."""
        self._relatch_ts = [x for x in self._relatch_ts if t - x <= self.relatch_win]
        self._relatch_ts.append(t)
        if len(self._relatch_ts) >= self.relatch_n:
            self.relatch_pending = True
            self._relatch_ts = []
            self._close(t, 'relatch')
            return True
        return False

    def open_reset_pending(self) -> bool:
        """Первое открытие ЖДЁТ обработки (флаг ещё не забрали). Нужно, чтобы
        отложить захват рамы до спокойного курса, не потратив флаг впустую."""
        return self._open_reset_pending

    def take_open_reset(self) -> bool:
        """Снять флаг «первое открытие: отдать сырой VINS, не усыновлять EKF»
        (один раз за полёт). ray_tracer по нему сбрасывает якорь и на время окна
        не латчит его заново — чтобы полётник успел пересесть на нашу раму."""
        p = self._open_reset_pending
        self._open_reset_pending = False
        return p

    def take_relatch(self) -> bool:
        """Снять флаг «латчить заново» (один раз)."""
        p = self.relatch_pending
        self.relatch_pending = False
        return p

    def is_open(self, t) -> bool:
        return t >= self._closed_until

    def reset(self):
        """Наш /restart VINS: поток объявлен новым (следующая одометрия не
        сравнивается с прошлой — она из другой рамы), якорь заново."""
        self._prev = None
        self.relatch_pending = True

    # --- внутреннее -----------------------------------------------------------
    def _close(self, t, reason):
        if self.is_open(t):
            self.closes += 1
        self.reason = reason
        self._closed_until = max(self._closed_until, t + self.hold_sec)

    def state_line(self, t) -> str:
        """Строка /nn1/bridge: 'open|closed <причина> <подтяжек в окне> <закрытий> <перерождений>'."""
        return (f"{'open' if self.is_open(t) else 'closed'} {self.reason} "
                f"{len(self._relatch_ts)} {self.closes} {self.rebirths}")

def ready_verdict(ready, age, fresh_sec, required=True):
    """Что подать в `BridgeGate.on_odom(ready=…)` по вердикту зрелости лётной ноды.

    ЕСТЬ СВЕЖИЙ ВЕРДИКТ — он и есть ответ. НЕТ СВЕЖЕГО:
      - `required=True` (наш стек) → **False, мост ЗАКРЫТ**. Нет доказательства
        зрелости — нет и позы в EKF, это ровно смысл гейта;
      - `required=False` (голый стример без лётной ноды) → None, гейт зрелости не
        применяется, мост живёт своими проверками.

    ⚠️ ПОЧЕМУ НЕ «ПОДОЖДАТЬ ВЕРДИКТ N СЕКУНД ПОСЛЕ СТАРТА» (попытка 2026-09-09,
    провалилась в полёте): `ray_tracer` живёт со стеком, а лётная нода поднимается
    НА КАЖДЫЙ ПРОГОН и заговаривает через десятки секунд. Лог 170043:

        вердикта зрелости нет 10 с — считаю, что лётной ноды нет … мост живёт своими
        мост ОТКРЫТ впервые: 2 с отдаю VINS от своего начала (Δyaw=+128.2°, t=0)
        вердикт зрелости получен через 22.6 с после старта (первый: не зрел)

    то есть ожидание истекло за 12.6 с ДО первого вердикта, мост открылся, и в EKF
    ушла рама, залатченная на земле (+128.2° при истинном повороте +117.1°). Никакой
    фиксированный таймаут тут не работает — «ноды нет» надо ОБЪЯВЛЯТЬ ручкой, а не
    угадывать по времени. Разбор дыры и её цены — 192430, `cmd/yaw_ab/README.txt`.
    """
    if age < fresh_sec:
        return bool(ready)
    return False if required else None
