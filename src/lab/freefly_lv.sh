# Главное открытие реплея: с ИСТИННЫМИ углами Gazebo шум пути канала НЕ растёт с
# высотой (6–11 мм/кадр на 0.3–17.5 м), с углами MAVROS в полёте — 14 → 386 мм.
# Весь рост — тайминг ATTITUDE: «последнее пришедшее» держится ступенькой (~15–25
# Гц) × рычаг полосы 20–40 м/рад на 10–18 м. Реплей со ступенькой воспроизводит
# полёт (12.5 Гц: 463 мм на 17.5 м, 25 Гц: 196); дотяжка гиро (att_extrap) даёт
# лишь 285/122; интерполяция между двумя штампованными отсчётами — уровень
# «задержка 20 мс» ≈ 70 мм. Ориентация EKF сама точна (отстаёт от истины на 15–20
# мс, corr 1.000). Сделано:
# 1) BS_ATT_INTERP=1 — AttitudeBuffer: кадр ждёт следующий отсчёт ATTITUDE (≤ 1/темп,
#    не дольше BS_ATT_WAIT_MAX 0.15) и берёт угол интерполяцией; BS_ATT_LATENCY —
#    запас на транспорт MAVROS (штамп = приём), кандидат 0.02;
# 2) BS_PITCH_SOFT_NOISE / BS_ROLL_SOFT_NOISE (м/кадр) — мягкость по ИЗМЕРЕННОМУ
#    шуму канала (ipm_noise_*: EMA |Δпуть − v̂·dt|, реплей: corr 0.97–0.99 с истиной;
#    невязка МНК НЕ годится — недооценка 8×). Высота — суррогат: на 9.9 м модель
#    ∝ h ждала 0.82 м/с, было 0.39. Порог 0.02 ≈ 1.5× шума у земли (σ̂ 11–16 мм):
#    после интерполяции углов шум упадёт и soft сам вернётся к 1. С soft_alt —
#    минимум из двух. Стенд test_soft_alt (плант с шумом приращения ∝ h).
# В bag теперь пишется /mavros/imu/data (темп ATTITUDE и проверка интерполяции).
# Кандидат (шаг 1 — только интерполяция, высотная мягкость как в ab_soft):
#   BS_ATT_INTERP=1 BS_ATT_LATENCY=0.02 BS_PITCH_SOFT_ALT=2 WIND_SPD=5 \
#     NAME=ab_interp bash src/lab/freefly_lv.sh
# Смотреть: шум пути на 10/17.5 м (реплей/разбор) — с 101/386 мм к ~20/70; тангаж
# на высоте тише, чем в ab_soft; у земли без изменений. Шаг 2 (после): заменить
# высотную мягкость на шумовую — BS_PITCH_SOFT_ALT=0 BS_PITCH_SOFT_NOISE=0.02.
# ВЕРДИКТ ab_interp / ab_noise (2026-08-29, до 17–19 м; Андрей: «всё супер, оставил
# бы мягкость по шуму»). ATTITUDE в bag — 50 Гц (20 мс), т.е. в полёте была
# ступенька 20 мс + транспорт. Шум пути за кадр, мм (эталон ab_soft без интерп.):
#   ~0.5 м: 33 → 17/20;  5–7 м: 58 → 32/41;  10 м: 101 → 57/62;  17–19 м: 386 → 49/59
# — интерполяция сняла рост с высоты (17 м = уровень 10 м; пол с точными углами
# 6–11 мм — остаток EKF/LK). Тангаж на 10–19 м руки-прочь: ab_interp (мягкость по
# высоте, soft 0.12–0.19) PWM σ 51–56, тангаж σ 4°, брейк ≤1.4/10 с; ab_noise
# (по шуму, soft ≈ 0.57 — шум после интерполяции ниже) PWM σ 77, тангаж σ 5.5°,
# брейк ≤2.3/10 с — авторитета на высоте больше, качания нет (было PWM σ 109,
# тангаж 6.7°, брейк 33). С 2026-08-29 ДЕФОЛТ: BS_ATT_INTERP=1 BS_ATT_LATENCY=0.02
# BS_PITCH_SOFT_NOISE=0.02 (BS_PITCH_SOFT_ALT остаётся 0; крен без мягкости).
# Ручка на будущее: порог 0.02 → 0.015 даст на высоте soft ~0.4 (мягче), если
# захочется тише; выкл — BS_PITCH_SOFT_NOISE=0.
