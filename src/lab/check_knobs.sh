#!/usr/bin/env bash
# check_knobs.sh — ПАДАТЬ НА НЕЗНАКОМОЙ РУЧКЕ, а не лететь с дефолтом.
#
# ЗАЧЕМ. Ручка BS_* проходит три уровня проводки, и раньше КАЖДЫЙ молчал, если её
# там не было:
#   1. capture_scene.sh  — проброс в контейнер (был рукописный белый список);
#   2. bootstrap_arch2.sh — мост BS_FOO → --foo;
#   3. bootstrap_node.py  — argparse; BootstrapConfig(**vars(a)) собирается ровно из
#      разобранных аргументов, поэтому поле без аргумента МОЛЧА берёт дефолт датакласса.
# Свип B3s (BS_ROLL_RATE_KI=5) из-за дыры на всех трёх уровнях отлетел с ki=0: значение
# доехало до .env и меты прогона, но не до ноды. Полтора часа стенда и правдоподобный
# ложный вывод «интегратор не помогает».
#
# ⚠️ ДЕФОЛТ ТУТ НЕ ЗАЩИТА, А МАСКИРОВКА. Прошлые кампании уцелели только потому, что
# BS_IPM_WZ_TAU и BS_FENCE случайно задавались значениями, равными дефолтам (2.0 и 25).
# Свипни кто-нибудь τ по трём значениям — все три прогона отлетели бы с τ=2.0, дали бы
# одинаковый результат, и вывод «τ ни на что не влияет» было бы нечем опровергнуть.
#
# ЧТО ПРОВЕРЯЕТ (оба уровня — статически, за доли секунды, ДО подъёма стека):
#   1. каждая заданная в окружении BS_*/ARM_* где-то РАЗЫМЕНОВЫВАЕТСЯ ($BS_X) в src/lab.
#      Присваивание (BS_X=…) и упоминание в комментарии не считаются — иначе проверка
#      пропустила бы ровно тот случай, ради которого написана;
#   2. каждый флаг --foo, который bootstrap_arch2.sh умеет выдать, существует в argparse
#      bootstrap_node.py. Это ловит обрыв между 2-м и 3-м уровнем.
#
# Чего НЕ проверяет: что нода реально применяет значение (это уже вопрос recipes.py и
# стратегии). Сквозная проверка одна — грепнуть строку запуска ноды в логе прогона.
#
# Запуск (сам по себе, для ревью) и код возврата:
#   bash src/lab/check_knobs.sh          # 0 = чисто, 1 = найдена немая ручка
#   BS_ROLL_RATE_KI=5 bash src/lab/check_knobs.sh
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NODE="$SCRIPT_DIR/../mission/mission_pkg/nodes/bootstrap_node.py"
ARCH2="$SCRIPT_DIR/bootstrap_arch2.sh"
bad=0

# ── 1. заданные ручки против реально потребляемых ─────────────────────────────
# Ищем ТОЛЬКО разыменование: `$BS_X` / `${BS_X` / `${BS_X:-…}`. Присваивание не
# содержит `$` перед именем и потому в список известных не попадает — это и есть суть
# проверки: ручка, которую кто-то выставляет, но никто не читает.
known="$(grep -rhoE '\$\{?(BS_|ARM_)[A-Z0-9_]+' "$SCRIPT_DIR" 2>/dev/null \
         | sed 's/^\${\?//' | sort -u)"

while IFS= read -r name; do
    [ -z "$name" ] && continue
    # Пустая переменная = не задана: весь мост построен на `[ -n "${BS_X:-}" ]`.
    [ -z "${!name}" ] && continue
    if ! grep -qx "$name" <<< "$known"; then
        echo "ОШИБКА: ручка $name=${!name} задана, но НИКЕМ НЕ ЧИТАЕТСЯ." >&2
        echo "        Она доедет до .env и меты прогона, но не до ноды — прогон отлетит" >&2
        echo "        на дефолте и будет выглядеть настроенным. Опечатка в имени или" >&2
        echo "        не дописан мост в src/lab/bootstrap_arch2.sh." >&2
        bad=1
    fi
done < <(env | sed -n 's/^\(\(BS_\|ARM_\)[A-Z0-9_]*\)=.*/\1/p' | sort -u)

# ── 2. мост против argparse ───────────────────────────────────────────────────
if [ -r "$ARCH2" ] && [ -r "$NODE" ]; then
    args="$(grep -oE "add_argument\('--[a-z0-9-]+'" "$NODE" | sed "s/.*'--\(.*\)'/\1/" | sort -u)"
    while IFS= read -r flag; do
        [ -z "$flag" ] && continue
        if ! grep -qx "$flag" <<< "$args"; then
            echo "ОШИБКА: bootstrap_arch2.sh выдаёт --$flag, а argparse в bootstrap_node.py" >&2
            echo "        его не знает. Нода упадёт или (хуже) флаг молча пропадёт." >&2
            bad=1
        fi
    # (^|\s) — не матчить RARGS+=( (флаги joy_replay, не ноды): голое ARGS\+=\(
    # ловило их как подстроку и чекер горел на --scenario/--raw всегда
    done < <(grep -oE '(^|[[:space:]])ARGS\+=\(--[a-z0-9-]+' "$ARCH2" \
             | sed 's/.*(--//' | sort -u)
fi

[ "$bad" = "0" ] && echo "ручки: проводка целая"
exit "$bad"
