#!/usr/bin/env bash
# rate_gain_series.sh — СТАТИСТИКА по гейну rate-оси: серия из N прогонов на каждое
# значение `pitch_rate_kp`. Тот скрипт, которым гонялись серии F2 (kp=100) и F3 (kp=50).
#
# ЗАЧЕМ ИМЕННО СЕРИЯ, А НЕ СВИП. Свип F1 дал по одному прогону на точку, и этого не
# хватило: разброс стенда того же порядка, что разница между точками. Одна и та же
# настройка kp=200 дала СКО скорости 0.66 в серии E8 и 0.47 в F1a1, а разница между
# kp=100 и kp=50 в свипе — 0.18 против 0.31. Правило 8 в `tune.md`: на точку либо n≥3,
# либо вывод формулируется как направление, а не как победитель.
#
# КРИТЕРИЙ ВЫБОРА — СПОКОЙСТВИЕ, А НЕ БЛИЗОСТЬ. Демпфер живёт до инициализации VINS;
# позицию можно подтолкнуть стиком, а раскачка не корректируется ничем и сама портит
# параллакс и трекинг. Поэтому kp=200 не рассматривается, несмотря на ЛУЧШИЙ уход
# (1.7-4.8 м против 8-9 м): у него период 4.5 с и СКО скорости 0.54.
# Свип F1 (по прогону на точку):
#     kp   размах   v СКО   период   уход
#    200   1.90 м   0.54    4.5 с    1.7 м
#    100   9.20     0.18    нет      9.5
#     50   9.21     0.31    нет      7.9
# Гейном выбирается, какую болезнь терпеть: высокий держит близко но качается, низкий
# не качается но уползает. Обе разом лечит только позиционный член — отдельным слоем.
#
# ⚠️ Гейн rate-оси — ЭТО НЕ `BS_PITCH_KP`. Тот жил в log-единицах старого масштабного
# канала и к `DpPitchRate` отношения не имеет: у неё сигнал `ipm_vfwd` в М/С, ручка
# `BS_PITCH_RATE_KP` (дефолт 200 = PWM на 1 м/с).
# ⚠️ Стик до оси НЕ доходит: `pitch_rate_cmd_gain=0`, чистое удержание. Открывать его —
# отдельным шагом, иначе в серии окажется две переменные разом.
#
# Разбор — по СКО скорости и периоду (спокойствие) против сноса (плата):
#   python3 /lab/hold_quality.py /out/F2s1_bag   # бюджет спокойной жизни, пик, возврат
#   python3 /lab/axis_split.py   /out/F2s1_bag   # уход по осям и форма
#
# Запуск (отвязанно, чтобы пережил обрыв связи):
#   cd /root/13.17/docker/sim && setsid nohup env KP_LIST="100 50" N=5 \
#     bash /root/13.17/src/lab/rate_gain_series.sh > output/F2.log 2>&1 < /dev/null & disown
# Env: KP_LIST (значения гейна через пробел, "100 50"), N (прогонов на значение, 5),
#      PREFIX_BASE (имя-основа, "F"; серии выйдут F2s/F3s/...), остальное — как у
#      hover_series.sh.
set -u

KP_LIST="${KP_LIST:-100 50}"
N="${N:-5}"
PREFIX_BASE="${PREFIX_BASE:-F}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd /root/13.17/docker/sim

# Конфиг ОДИН на все значения: меняется ровно одна ручка, остальное прибито.
COMMON=(
    BS_STAB=DpHoldR BS_MISSION="climb3,hover20,land"
    BS_FENCE=25 BS_FLOW_OBS=1 BS_SLEW=300 BS_THROTTLE_CLIMB=1800
    BS_ARM_BUDGET=80 BS_CLIMB_BUDGET=120 BS_MODE_BUDGET=80 BS_LAND_BUDGET=180
    BS_ROLL_KP=48 BS_ROLL_KI=0 BS_ROLL_IMAX=150 BS_ROLL_SMOOTH=25
    BS_ROLL_OSIGN=1 BS_ROLL_CMD_GAIN=10
    BS_PITCH_OSIGN=1
    BS_YAW_KP=20 BS_YAW_KI=0 BS_YAW_SMOOTH=5
)

i=2
for kp in $KP_LIST; do
    name="${PREFIX_BASE}${i}s"
    echo "======== СЕРИЯ ${name}: pitch_rate_kp=${kp}, n=${N} ========"
    env N="$N" PREFIX="$name" GDRIVE_UP=1 MP4=1 BS_PITCH_RATE_KP="$kp" "${COMMON[@]}" \
        bash "$SCRIPT_DIR/hover_series.sh"
    df -h / | tail -1
    i=$((i + 1))
done
echo "######## СЕРИИ ПО ГЕЙНУ ЗАВЕРШЕНЫ (${KP_LIST}) ########"
