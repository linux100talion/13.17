#!/usr/bin/env python3
"""VinsTrack — скорость VINS конечной разностью ПО ШТАМПАМ + детект перерождения.

Урок прогона lv2_joy_20260905_114248 (разбор — control.md, «Гейт здоровья»):
скорость VINS в снапшоте считалась Δpose/Δt с dt по sim-времени ПРИХОДА
одометрии. Эстиматор на ноуте замирал на 1–3 с и догонял пачкой (14 сообщений
за 0.7 с при штампах ровно через 0.10 с) — dt вдвое короче, скорость вдвое
выше: 2.05→3.44 м/с при twist ≤1.47 и истине ≤1.7. Гейт висения принял
артефакт за разнос → демоут + /restart в полёте → VINS переродился под порывом
с масштабом 0.14 → унос ±50 м. Тот же урок для детектора зрелости уже был
выучен (ripeness: время — header-штамп); здесь он доведён до скорости.

Штамп одометрии — sim-время КАДРА (камера штампует часами ноды), то есть время
измерения; приход = измерение + задержка обработки, и джиттер обработки в
скорость попадать не должен. dt по штампам: стопор эстиматора не меняет
скорость вовсе (штампы регулярны, меняется только очередь доставки).

ПЕРЕРОЖДЕНИЕ (рестарт/переинициализация): поток молчит в INITIAL ≥1 с (окно
инициализации 10 кадров @10 Гц), новая рама стартует из нуля → дыра в штампах
> gap_sec ИЛИ скачок позы быстрее физического потолка v_jump. У стопора дыры в
штампах НЕТ (они регулярны) — так стопор и перерождение различаются сами. На
перерождении скорость обнуляется (EMA с чистого листа), вызывающий сбрасывает
зрелость потока (счётчик/первое время) — ярус 1 ждёт зрелость заново.

Чистый python без ROS: кормится RosTelemetry._on_odom, тест — test_vins_track.py.
"""
import math


class VinsTrack:
    def __init__(self, ema_a: float = 0.4, gap_sec: float = 1.0,
                 v_jump: float = 12.0):
        self.ema_a = ema_a
        self.gap_sec = gap_sec
        self.v_jump = v_jump
        self.vx = 0.0
        self.vy = 0.0
        self._prev = None            # (t_stamp, x, y) прошлого отсчёта

    def reset(self) -> None:
        """Поток объявлен оборванным (нода послала /restart): следующий отсчёт —
        первый новой рамы, скорость с нуля. Перерождением НЕ считается (его
        уже учёл вызывающий)."""
        self._prev = None
        self.vx = self.vy = 0.0

    def on_odom(self, t: float, x: float, y: float) -> bool:
        """t — header-штамп одометрии (sim-время кадра). Возвращает True, если
        этот отсчёт открывает ПЕРЕРОЖДЁННЫЙ поток (дыра в штампах или скачок)."""
        if self._prev is None:
            self._prev = (t, x, y)
            return False
        pt, px, py = self._prev
        dt = t - pt
        if dt <= 0.0:
            return False                     # дубликат/беспорядок штампов — пропуск
        dx, dy = x - px, y - py
        reborn = dt > self.gap_sec or math.hypot(dx, dy) / dt > self.v_jump
        if reborn:
            self.vx = self.vy = 0.0
        else:
            a = self.ema_a
            self.vx = (1.0 - a) * self.vx + a * dx / dt
            self.vy = (1.0 - a) * self.vy + a * dy / dt
        self._prev = (t, x, y)
        return reborn
