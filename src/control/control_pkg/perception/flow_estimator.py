    def _vel_mask(self, gray):
        """Маска для набора СКОРОСТИ: только нижняя часть кадра (ближняя земля)."""
        if self.feat_lo <= 0:
            return None
        if self._mask_vel is None or self._mask_vel.shape != gray.shape:
            m = np.zeros(gray.shape, np.uint8)
            m[int(self.feat_lo * gray.shape[0]):, :] = 255
            self._mask_vel = m
        return self._mask_vel

    def _rot_flow(self, p0, wx, wy, wz, dt):
        """Вращательный поток (пиксели/кадр) в точках p0 для ω камеры (rad/s)."""
        # нормированные координаты
        xn = (p0[:, 0] - self.cx) / self.fx
        yn = (p0[:, 1] - self.cy) / self.fy
        # Longuet-Higgins/Prazdny, нормир. плоскость, ×dt. TODO[sign]: знаки сверяет тест.
        u_rot_n = (xn * yn * wx - (1.0 + xn ** 2) * wy + yn * wz) * dt
        v_rot_n = ((1.0 + yn ** 2) * wx - xn * yn * wy - xn * wz) * dt
        u_rot = self.fx * u_rot_n
        v_rot = self.fy * v_rot_n
        return np.column_stack([u_rot, v_rot])

    # ------------------------------------------------------------- вид сверху
    def _ipm_px(self, X, Y, h, pitch, roll):
        """Точка земли (X вперёд, Y вправо, глубина h) → пиксель кадра. None вне кадра.

        Оси камеры: x вправо, y вниз, z вперёд. Модель выбирается `ipm_model`.

        ⚠️ УГЛЫ ПРИХОДЯТ В СИСТЕМЕ ROS (ENU/FLU: y ВЛЕВО, z ВВЕРХ), а не в авиационной
        FRD. По правилу правой руки вокруг оси «влево» вектор вперёд уходит ВНИЗ, то есть
        ПОЛОЖИТЕЛЬНЫЙ ТАНГАЖ ЗДЕСЬ = НОС ВНИЗ. Поэтому `cam_tilt + pitch` ВЕРНО: нос вниз
        увеличивает угол взгляда вниз. Это проверено замером, а не рассуждением: попытка
        «исправить» знак на `cam_tilt − pitch` разнесла продольный масштаб с 1.10 до 4.06
        при ошибке 2.64 м/с вместо 0.40 (стенд `att_extrap_test.py`, бэг I1s1).
        Ошибка вывода была в том, что эталонная цепочка выводилась в FRD, где знак
        обратный. Не повторять: конвенцию углов проверять ЧИСЛЕННО, до правки.

        `legacy` — лётная модель, на ней отлетаны серии E8-H2: наклон `cam_tilt + pitch`
        вокруг оси x, затем крен вокруг ОПТИЧЕСКОЙ оси.
        `rsign`  — то же, но крен на −φ. Изолирует ЗНАК КРЕНА: тангаж не трогает.
        `exact`  — честная цепочка: точка (X вперёд, Y вправо, h вниз) → корпус
                   `Rx(φ)·Ry(−θ)` (минус — перевод тангажа ROS→FRD) → камера матрицей
                   крепления `M(cam_tilt)`. Отличается от `legacy` тем, что крен идёт
                   вокруг ПРОДОЛЬНОЙ оси корпуса, наклонённой к оптической на `cam_tilt`,
                   а не вокруг самой оптической.

        ⚠️ `cam_tilt + pitch` живёт ещё в двух местах (наклонная поправка опоры и строка
        горизонта для подгонки курса). Там знак НЕ трогали: это отдельные каналы, и
        менять их надо своим замером, а не заодно."""
        if self.ipm_model == 'exact':
            cr, sr = math.cos(roll), math.sin(roll)
            cp, sp = math.cos(-pitch), math.sin(-pitch)
            ct, stl = math.cos(self.cam_tilt), math.sin(self.cam_tilt)
            Rx = np.array([[1.0, 0.0, 0.0], [0.0, cr, sr], [0.0, -sr, cr]])
            Ry = np.array([[cp, 0.0, -sp], [0.0, 1.0, 0.0], [sp, 0.0, cp]])
            M = np.array([[0.0, 1.0, 0.0], [-stl, 0.0, ct], [ct, 0.0, stl]])
            P = M @ (Rx @ (Ry @ np.array([X, Y, h], dtype=np.float64)))
        else:
            rs = -1.0 if self.ipm_model == 'rsign' else +1.0
            a_down = self.cam_tilt + pitch
            ca, sa = math.cos(a_down), math.sin(a_down)
            cr, sr = math.cos(rs * roll), math.sin(rs * roll)
            P = np.array([[cr, -sr, 0.0], [sr, cr, 0.0], [0.0, 0.0, 1.0]]) @ (
                np.array([[1.0, 0.0, 0.0], [0.0, ca, -sa], [0.0, sa, ca]])
                @ np.array([Y, h, X], dtype=np.float64))
        if P[2] <= 0.05:
            return None
        return [self.cx + self.fx * P[0] / P[2], self.cy + self.fy * P[1] / P[2]]

    _VEL_HOLD = 1.0     # сек: сколько мостим провал измерений чистым прогнозом

    def _vel_reset(self):
        """Скорость с фильтром — только в воздухе: на земле/без баро состояние 0."""
        self._ipm_v = [0.0, 0.0]
        self._ipm_v_t = None
        self._ipm_meas_t = -1e9

    def _vel_predict(self, stamp, pitch, roll, wz):
        """Прогноз скорости на кадр: наклон тяги + поворот body-осей рысканием.

        Знаки — в конвенции канала (см. _ipm_px): pitch>0 = нос ВНИЗ → разгон
        вперёд (+vfwd); roll>0 = правое крыло вниз → разгон вправо, а vlat у нас
        ЛЕВО-положителен → минус. wz>0 = разворот влево: продольная и боковая
        компоненты скорости перетекают друг в друга (−ω×v).
        ⚠️ Оба знака наклона подлежат ЧИСЛЕННОЙ полётной проверке до включения
        лётного дефолта — печальный опыт выведенных знаков задокументирован
        в _ipm_px."""
        if self._ipm_v_t is None:
            self._ipm_v_t = stamp
            return
        dt = min(max(stamp - self._ipm_v_t, 0.0), 0.2)
        self._ipm_v_t = stamp
        vf, vl = self._ipm_v
        af = 9.81 * math.sin(pitch)
        al = -9.81 * math.sin(roll)
        self._ipm_v[0] = vf + (af + wz * vl) * dt
        self._ipm_v[1] = vl + (al - wz * vf) * dt
        if stamp - self._ipm_meas_t <= self._VEL_HOLD:
            self.ipm_vfwd, self.ipm_vlat = self._ipm_v

    def _ipm_window(self, h, pitch):
        """Начало полосы ЭТОГО кадра: базовое x0 или отодвинутое до границы видимости.

        Граница: земля на дистанции X видна, пока atan(h/X) не глубже нижнего края
        кадра a = cam_tilt + pitch + atan(cy/fy). pitch — в конвенции канала (ROS,
        положительный = нос ВНИЗ, как в `_ipm_px` legacy), то есть клевок опускает
        границу ближе, задирание носа — отодвигает. Запас ipm_adapt (≈1.05) держит
        ближний край окна чуть дальше границы: на самой кромке фичи полугаснут.
        None = полосы не видно вовсе (взгляд у горизонта)."""
        if self.ipm_adapt <= 0.0:
            return self.ipm_x0
        a = self.cam_tilt + pitch + math.atan2(self.cy, self.fy)
        if a >= 0.5 * math.pi:          # смотрим отвесно вниз — видно всё
            return self.ipm_x0
        if a <= 0.05:                   # нос задран к горизонту — полосы нет
            return None
        return max(self.ipm_x0, self.ipm_adapt * h / math.tan(a))

    def _ipm_rectify(self, gray, h, pitch, roll, x0=None, x1=None):
        """Полоса земли → метрический вид сверху (1 пиксель = ipm_res метров).
        x0/x1 — окно этого кадра (None = базовое, для офлайн-инструментов)."""
        if x0 is None:
            x0 = self.ipm_x0
        if x1 is None:
            x1 = self.ipm_x1
        src = []
        for X, Y in ((x0, -self.ipm_yhalf), (x0, self.ipm_yhalf),
                     (x1, self.ipm_yhalf), (x1, -self.ipm_yhalf)):
            p = self._ipm_px(X, Y, h, pitch, roll)
            if p is None:
                return None
            src.append(p)
        src = np.array(src, dtype=np.float32)
        if src[:, 0].min() < -2 * self.cx or src[:, 0].max() > 4 * self.cx:
            return None                     # полоса ушла далеко за кадр — доверять нечему
        w = max(8, int(2 * self.ipm_yhalf / self.ipm_res))
        hh = max(8, int((x1 - x0) / self.ipm_res))
        dst = np.array([[0, hh - 1], [w - 1, hh - 1], [w - 1, 0], [0, 0]], dtype=np.float32)
        return cv2.warpPerspective(gray, cv2.getPerspectiveTransform(src, dst), (w, hh))

    def _wz_debias(self, stamp, wz):
        """ω_z без постоянной составляющей (ФВЧ первого порядка, τ = ipm_wz_tau).

        Оценка смещения ведётся ВСЕГДА, пока идут кадры, — в том числе на земле и на
        подъёме, где борт ещё не разворачивается и среднее чище всего. Ручка 0 отдаёт ω_z
        как есть (прежнее поведение)."""
        wz = float(wz)
        if self.ipm_wz_tau <= 0.0:
            return wz
        if self._wz_bias is None:
            self._wz_bias = wz          # старт с первого отсчёта, а не с нуля: иначе первые
            self._wz_t = stamp          # τ секунд поправка работала бы по СЫРОМУ смещению
            self._wz_n = 1
            return 0.0
        dt = stamp - self._wz_t
        self._wz_t = stamp
        self._wz_n += 1
        if dt > 0.0:
            # ⚠️ РАЗГОН ОЦЕНКИ. Один отсчёт ω_z шумит на 0.13 рад/с — вшестеро больше самого
            # смещения (0.02). Чистое экспоненциальное сглаживание стартует ИМЕННО с такого
            # отсчёта и тащит его ошибку τ секунд: при τ=10 и прогреве 8 с в оценке остаётся
            # 43% начального промаха, и длинное τ выходило ХУЖЕ короткого (замер по I1s1:
            # сдвиг τ=3 −0.01, τ=5 +0.03, τ=10 +0.17 — порядок обратный физике).
            # Поэтому вес отсчёта берётся не меньше 1/n: пока набрано меньше τ/dt отсчётов,
            # это ТОЧНОЕ среднее по всему, что пришло, и лишь дальше — забывающее окно τ.
            a = max(1.0 - math.exp(-dt / self.ipm_wz_tau), 1.0 / self._wz_n)
            self._wz_bias += a * (wz - self._wz_bias)
        return wz - self._wz_bias

    def _ipm_update(self, gray, stamp, alt, pitch, roll, wz=0.0):
        """Шаг канала вида сверху: путь в метрах + скорость наклоном МНК в окне."""
        wz = self._wz_debias(stamp, wz)
        self.ipm_ok = False
        if not self.ipm or alt is None or alt < 0.5:
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_x0 = None
            self._vel_reset()
            return
        if self.ipm_vel_tau > 0.0:
            # прогноз тикает на КАЖДОМ кадре, включая бракованные — провалы мостятся;
            # ipm_ok при фильтре = «скорости можно верить» (измерения свежее _VEL_HOLD)
            self._vel_predict(stamp, pitch, roll, wz)
            self.ipm_ok = (stamp - self._ipm_meas_t) <= self._VEL_HOLD
        x0 = self._ipm_window(alt, pitch)
        if x0 is None:
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_x0 = None
            return
        x1 = x0 + (self.ipm_x1 - self.ipm_x0)
        rect = self._ipm_rectify(gray, alt, pitch, roll, x0, x1)
        if rect is None:
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_x0 = None
            return
        prev = self._ipm_prev
        prev_t = self._ipm_prev_t
        prev_x0 = self._ipm_prev_x0
        # ⚠️ ВРЕМЯ ОПОРНОГО КАДРА ОБНОВЛЯЕТСЯ ЗДЕСЬ ЖЕ, вместе с самим кадром. Раньше оно
        # ставилось в конце, после успешного шага потока, и три ранних `return` ниже (мало
        # точек, мало выживших, смена размера) сдвигали КАДР, но не ВРЕМЯ. Тогда `dpsi`
        # считался по интервалу в несколько кадров вместо одного и вычитал разворот кратно
        # сильнее нужного. Офлайн на спокойном бэге срывов почти нет — стенд это пропустил;
        # в полёте на трясущемся борту канал уходил вразнос (серия K2s: продольная СКО
        # 2.06-2.44 м/с в трёх прогонах из пяти против 0.11-0.23 в остальных).
        self._ipm_prev = rect
        self._ipm_prev_t = stamp
        self._ipm_prev_x0 = x0
        if prev is None or prev.shape != rect.shape:
            return
        pts = self._detect(prev)
        if pts is None or len(pts) < 20:
            return
        pts = pts.reshape(-1, 1, 2).astype(np.float32)
        p1, st, _ = cv2.calcOpticalFlowPyrLK(prev, rect, pts, None, **self._lk)
        p0b, st2, _ = cv2.calcOpticalFlowPyrLK(rect, prev, p1, None, **self._lk)
        ok = (st.reshape(-1) == 1) & (st2.reshape(-1) == 1)
        ok &= np.linalg.norm(p0b.reshape(-1, 2) - pts.reshape(-1, 2), axis=1) < 1.0
        if ok.sum() < 15:
            return
        p0 = pts.reshape(-1, 2)[ok]
        d = p1.reshape(-1, 2)[ok] - p0
        # --- ВЫЧИТАНИЕ РАЗВОРОТА (ipm_derot) ---
        # Медиана смещений считает поле «только сдвиг», поэтому разворот борта читается
        # как боковой снос: полоса лежит ВПЕРЕДИ, и поворот на dψ двигает её вбок на
        # X·dψ (X = 3…6 м), то есть на порядок сильнее, чем сам разворот виден в полосе.
        # Оценивать dψ ЗДЕСЬ не надо и вредно: плечо 3→6 м слабое, а гироскоп даёт ω_up
        # прямо и точно. Поэтому предсказанное вращательное поле ВЫЧИТАЕТСЯ поточечно,
        # а медиана остаётся на месте со всей своей устойчивостью к выбросам (сцена не
        # плоская: стены и здания дают параллакс, МНК бы на них поехал).
        # Геометрия: точка сетки (столбец u, строка v) ↔ земля Y = u·res − yhalf (вправо),
        # X = x1 − v·res (вперёд). Разворот влево на dψ: dX = −Y·dψ, dY = +X·dψ, значит
        # в сетке d_столбец = +X·dψ/res, d_строка = +Y·dψ/res.
        # ⚠️ ЗНАК ручкой, а не выводом. В этой кампании два знака подряд были выведены
        # неверно (крен в проекции, тангаж в ROS-конвенции), оба поймал замер. `ipm_derot`
        # = 0 (выкл) / +1 / −1, выбирается стендом att_extrap_test.py по одним кадрам.
        if self.ipm_derot and prev_t is not None:
            dpsi = self.ipm_derot * float(wz) * (stamp - prev_t)
            if abs(dpsi) > 1e-9:
                Yg = p0[:, 0] * self.ipm_res - self.ipm_yhalf
                # p0 живут в сетке ПРОШЛОГО кадра → дальний край его окна
                Xg = (prev_x0 + (self.ipm_x1 - self.ipm_x0)) - p0[:, 1] * self.ipm_res
                d = d - np.column_stack([Xg * dpsi / self.ipm_res,
                                         Yg * dpsi / self.ipm_res])
        # столбец = Y вправо, строка = X вперёд (строка 0 — дальний край). Это оси
        # СЕТКИ, а не знака скорости борта: фичи в полосе движутся ПРОТИВ хода борта.
        # Продольная крутизна к скорости борта +1.00/+1.03/+0.97 (вперёд = плюс).
        # ⚠️ Боковая: ipm_lat/ipm_vlat ЛЕВО-положительны. Старая калибровка
        # «+0.91/+1.06/+1.09 вправо» мерялась против twist.y в предположении FRD,
        # а body-twist Gazebo — FLU (y = влево); перезамер полёта 2026-08-18 по
        # производной мировой позиции дал ipm_vlat ≈ −v_right с наклоном ~1.
        # Потребитель (DpRollRate._cmd) компенсирует минусом, как DpRollHold.
        self.ipm_lat += float(np.median(d[:, 0])) * self.ipm_res
        # Сдвиг АДАПТИВНОГО окна между кадрами (x0 − prev_x0) неотличим для потока от
        # хода вперёд (статичная точка земли сползает вниз по сетке ровно на сдвиг),
        # но он известен ТОЧНО — вычитаем. При ipm_adapt=0 окна совпадают, дельта 0.
        self.ipm_fwd += float(np.median(d[:, 1])) * self.ipm_res - (x0 - prev_x0)
        self.ipm_ok = True
        self._ipm_meas_t = stamp
        self._ipm_hist.append((stamp, self.ipm_fwd, self.ipm_lat))
        while self._ipm_hist and stamp - self._ipm_hist[0][0] > self.ipm_win:
            self._ipm_hist.pop(0)
        if len(self._ipm_hist) >= 4:
            a = np.array(self._ipm_hist)
            tc = a[:, 0] - a[:, 0].mean()
            den = float(np.dot(tc, tc))
            if den > 0 and a[-1, 0] - a[0, 0] > 0.5 * self.ipm_win:
                sf = float(np.dot(tc, a[:, 1] - a[:, 1].mean()) / den)
                sl = float(np.dot(tc, a[:, 2] - a[:, 2].mean()) / den)
                if self.ipm_vel_tau > 0.0:
                    # комплементарная коррекция прогноза к МНК-наклону: быстрые
                    # движения несёт прогноз (без лага), постоянную составляющую —
                    # измерение (без дрейфа наклонного смещения EKF)
                    k = (min(1.0, max(0.0, stamp - prev_t) / self.ipm_vel_tau)
                         if prev_t is not None else 1.0)
                    self._ipm_v[0] += k * (sf - self._ipm_v[0])
                    self._ipm_v[1] += k * (sl - self._ipm_v[1])
                    self.ipm_vfwd, self.ipm_vlat = self._ipm_v
                else:
                    self.ipm_vfwd, self.ipm_vlat = sf, sl

    # ---------------------------------------------------------------- опора
    def reset_keyframe(self):   # noqa: D401 — накопитель тоже обнуляется, см. ниже
        """Сбросить опору: следующий кадр станет новым опорным (точка удержания).

        Зовётся управляющим слоем на входе в сегмент удержания — как `enter()` у
        стабилизаторов. Позиция, которую отдаёт опорный канал, отсчитывается ОТ
        этого кадра; вернуться борт может только туда, что видит."""
        self._kf_pending = True
        self.kf_acc = 0.0       # новая точка удержания — счёт с нуля
        self.kf_segs = 0
        self._kf_hist = []      # положение отсчитывается заново → окно скорости тоже
        self.kf_vel = 0.0
        self.ipm_fwd = self.ipm_lat = 0.0   # путь вида сверху — от новой точки удержания
        self._ipm_hist = []
        self._ipm_prev_t = None
        self._alt_out = 0.0     # заморозка по высоте — тоже заново

    def _kf_vel_update(self, stamp, kf_logs, kf_ok):
        """Скорость опоры = наклон МНК по окну kf_win секунд (см. ctor).

        Недостоверные кадры в окно НЕ кладём: их значение — задержанная копия
        прошлого, и наклон по ним занижен. Окно при этом не чистим — вернётся
        достоверность, вернётся и оценка, а пропуск в 2-3 кадра наклону не мешает.
        """
        if kf_ok:
            self._kf_hist.append((float(stamp), float(kf_logs)))
        self._kf_hist = [p for p in self._kf_hist if stamp - p[0] <= self.kf_win]
        if len(self._kf_hist) < 4:
            self.kf_vel = 0.0
            return
        ts = np.array([p[0] for p in self._kf_hist])
        vs = np.array([p[1] for p in self._kf_hist])
        span = ts[-1] - ts[0]
        if span < 0.5 * self.kf_win:     # окно ещё не набралось (вход в сегмент)
            self.kf_vel = 0.0
            return
        tc = ts - ts.mean()
        self.kf_vel = float(np.dot(tc, vs - vs.mean()) / np.dot(tc, tc))

    def _seed(self, gray):
        """Посеять точки и сделать текущий кадр опорным."""
        pts = self._detect(gray)
        if pts is None or len(pts) < 8:
            self.kf_ref = self.kf_cur = None
            return False
        self._kf_logs_prev = None                   # новая опора — новый отсчёт
        self._kf_reject_run = 0
        self._kf_buf = []
        self.kf_ref = pts.reshape(-1, 2).copy()     # где точки были в ОПОРНОМ кадре
        self.kf_cur = pts.reshape(-1, 2).copy()     # где они сейчас (1:1 с kf_ref)
        self.kf_n0 = len(pts)                       # сколько посеяли — база для conf
        self.kf_age = 0
        self._kf_pending = False
        return True

    def _similarity(self):
        """Подобие опорный→текущий: (dx, dy, масштаб, поворот) или None.

        ⚠️ dx/dy — НЕ чистое смещение борта: поворот камеры по тангажу/курсу даёт
        такой же сдвиг картинки. Масштаб к вращению нечувствителен (первый порядок),
        поэтому продольный канал по нему честен, а боковой требует компенсации по
        углам — она пока не сделана, `kf_rot` отдаётся для диагностики."""
        if self.kf_ref is None or len(self.kf_ref) < self.kf_min_pts:
            return None
        M, _ = cv2.estimateAffinePartial2D(self.kf_ref, self.kf_cur,
                                           method=cv2.RANSAC, ransacReprojThreshold=2.0)
        if M is None:
            return None
        s = float(math.hypot(M[0, 0], M[0, 1]))
        rot = float(math.atan2(M[1, 0], M[0, 0]))
        return float(M[0, 2]), float(M[1, 2]), s, rot

    def _tilt_term(self, pitch):
        """log отношения дальностей из-за наклона борта: log(sin(α+θ)/sin(α+θ_опоры))."""
        a1 = math.sin(self.cam_tilt + pitch)
        a0 = math.sin(self.cam_tilt + self._kf_pitch0)
        if a1 <= 1e-3 or a0 <= 1e-3:
            return 0.0
        return math.log(a1 / a0)

    def process(self, gray, stamp, omega_imu, pitch=0.0, alt=None, roll=0.0):
        """gray: uint8 HxW; stamp: сек; omega_imu: ω в FLU (rad/s);
        pitch: тангаж борта, рад (>0 = нос ВНИЗ) — компенсация наклона;
        alt: высота (баро), м — опора действительна только пока она не ушла. → dict|None."""
        alt_drift = 0.0
        if alt is not None and self._kf_alt0 and alt > 0.2:
            alt_drift = abs(math.log(alt / self._kf_alt0))
        # ЗАМОРОЗКА: высота ушла — масштаб испорчен ЕЮ, а не движением (см. __init__).
        frozen = alt_drift > self.kf_alt_max
        dt_frame = 0.0 if self.prev_stamp is None else max(0.0, stamp - self.prev_stamp)
        self._alt_out = (self._alt_out + dt_frame) if frozen else 0.0
        # ω в FLU: z — ось ВВЕРХ, то есть ω_z и есть скорость разворота (см. ipm_derot).
        wz = float(np.asarray(omega_imu, dtype=np.float64).reshape(-1)[2])
        self._ipm_update(gray, stamp, alt, pitch, roll, wz)
        out = None
        if self.prev_gray is not None and self.vel_pts is not None and len(self.vel_pts) > 0:
            dt = max(1e-3, stamp - self.prev_stamp)
            # --- НАБОР СКОРОСТИ: свежие точки предыдущего кадра → текущий ---
            vp = self.vel_pts.reshape(-1, 1, 2).astype(np.float32)
            nxt, st, _ = cv2.calcOpticalFlowPyrLK(self.prev_gray, gray, vp, None, **self._lk)
            st = st.reshape(-1).astype(bool)
            p0 = vp.reshape(-1, 2)[st]
            p1 = nxt.reshape(-1, 2)[st]
            # --- НАБОР ОПОРЫ: свой КЛТ с обратной проверкой (отсев переприлипших) ---
            if self.kf_cur is not None and len(self.kf_cur) > 0:
                kp_prev = self.kf_cur.reshape(-1, 1, 2).astype(np.float32)
                knx, kst, _ = cv2.calcOpticalFlowPyrLK(self.prev_gray, gray, kp_prev,
                                                       None, **self._lk)
                kback, kst2, _ = cv2.calcOpticalFlowPyrLK(gray, self.prev_gray, knx,
                                                          None, **self._lk)
                kok = kst.reshape(-1).astype(bool) & kst2.reshape(-1).astype(bool)
                kok &= np.linalg.norm(kback.reshape(-1, 2) - kp_prev.reshape(-1, 2),
                                      axis=1) < 1.0
                # опора: выжившие точки — и в текущем наборе, и в опорном, строго 1:1
                self.kf_ref = self.kf_ref[kok]
                self.kf_cur = knx.reshape(-1, 2)[kok].copy()
                self.kf_age += 1
            n = len(p0)
            if n >= 8:
                flow = p1 - p0                                  # измеренный поток (px/кадр)
                # ω в фрейме камеры: ω_cam = R · ω_imu
                w = self.R @ np.asarray(omega_imu, dtype=np.float64)
                if self.rotflow_sign != 0.0:
                    rot = self.rotflow_sign * self._rot_flow(p0, w[0], w[1], w[2], dt)
                else:
                    rot = np.zeros_like(flow)                   # baseline: без derotation
                tr = flow - rot                                 # трансляционный остаток
                lateral_raw = float(np.median(tr[:, 0]))        # v0: прокси бокового сноса
                # временное сглаживание (медиана по N кадрам) — режет белый шум ~√N
                self._lat_buf.append(lateral_raw)
                if len(self._lat_buf) > self.roll_smooth_n:
                    self._lat_buf.pop(0)
                lateral = float(np.median(self._lat_buf)) if self.roll_smooth_n > 1 else lateral_raw
                # --- ВИЗУАЛЬНЫЙ YAW (фаза 2): derotate ТОЛЬКО roll+pitch (гиро x,y —
                # гравитация-референс, НЕ дрейфуют), yaw гиро НЕ вычитаем → остаток =
                # yaw-вращение + трансляция. В ДАЛЬНЕЙ сцене трансляция ≈0 (тот самый
                # depth, что убил боковую ось) → остаток ≈ чистый визуальный yaw.
                # ⚠️ ПРЕДПОЛОЖЕНИЕ «трансляция ≈0» ЛОМАЕТСЯ ДВИЖЕНИЕМ. Замер (yaw_fidelity.py,
                # доля истинного разворота, увиденная сигналом): ось курса одна, соседи на
                # оракулах (борт стоит) — +0.96 ± 0.12; три оси на Dp, борт идёт 1-4 м/с
                # (E2) — −0.09 ± 0.02; без стабилизации вовсе — −10. Точки выстраиваются
                # по СКОРОСТИ борта, а не по числу осей: медиану горизонтального потока
                # заливает снос, контур нулит снос вместо курса, курс уходит на 23…360°.
                #
                # Разделяем их ГЕОМЕТРИЕЙ, а не гироскопом (вычесть yaw-гиро нельзя — тогда
                # визуальный курс выродится в гироскоп со всем его дрейфом, ради чего его и
                # не вычитали). Для наклонённой вниз камеры дальность до земли растёт к
                # горизонту, поэтому горизонтальный поток от ТРАНСЛЯЦИИ ∝ 1/Z ∝ (y − y_гор),
                # а от ВРАЩЕНИЯ почти не зависит от строки. Значит линейная подгонка
                # u(y) = a + b·(y − y_гор) разносит их: b — снос, свободный член a —
                # вращение (там, где трансляции нет по построению: на бесконечности).
                oi = np.asarray(omega_imu, dtype=np.float64)
                w_ny = self.R @ np.array([oi[0], oi[1], 0.0])   # FLU: yaw (z) обнулён
                rot_ny = self._rot_flow(p0, w_ny[0], w_ny[1], w_ny[2], dt)
                u_ny = (flow - rot_ny)[:, 0]                    # yaw-вращение + трансляция
                yaw_flow_raw = float(np.median(u_ny))           # старый закон — как fallback
                if self.yaw_trans_fix:
                    # строка горизонта: камера смотрит вниз на (cam_tilt + pitch)
                    a_dn = self.cam_tilt + pitch
                    if a_dn > 1e-3:
                        yh = self.cy - self.fy * math.tan(a_dn)
                        dy = p0[:, 1] - yh
                        # подгонка осмысленна только когда точки РАЗНЕСЕНЫ по строкам:
                        # на узкой полосе наклон не определён и вылезет мусор в свободном члене
                        if float(np.ptp(dy)) > 0.15 * self.cy:
                            b, a0 = np.polyfit(dy, u_ny, 1)
                            yaw_flow_raw = float(a0)
                        # ⚠️ ЭКСТРАПОЛЯЦИЯ ДЛИННАЯ. Точки канала скорости живут ПОД маской
                        # feat_lo (нижняя треть кадра), а горизонт — выше неё на сотни
                        # строк, поэтому свободный член берётся далеко за пределами данных
                        # и шум наклона попадает в него с плечом. На синтетике (шума нет)
                        # это не видно: yaw_trans_test даёт остаток сноса 0.014 px/кадр
                        # против 8.9 у прежнего закона. На реальных кадрах проверять
                        # отдельно — переигрыванием бэга с сохранёнными /image_color.
                self._yaw_buf.append(yaw_flow_raw)                  # сглаживание (медиана по N)
                if len(self._yaw_buf) > self.yaw_smooth_n:
                    self._yaw_buf.pop(0)
                yaw_flow = float(np.median(self._yaw_buf)) if self.yaw_smooth_n > 1 else yaw_flow_raw
                # --- ПРОДОЛЬНАЯ ось (phase2, looming): два кандидата сигнала из tr.
                # longitudinal = медиана ВЕРТИКАЛЬНОГО остатка (для down-tilt камеры ∝
                # продольной скорости; прямой аналог lateral по оси Y).
                longitudinal_raw = float(np.median(tr[:, 1]))
                self._lon_buf.append(longitudinal_raw)          # сглаживание — как у roll
                if len(self._lon_buf) > self.pitch_smooth_n:
                    self._lon_buf.pop(0)
                longitudinal = (float(np.median(self._lon_buf)) if self.pitch_smooth_n > 1
                                else longitudinal_raw)
                # divergence = расширение поля из АФФИННОГО фита tr ~ [1, xn, yn]:
                # ∂u/∂xn + ∂v/∂yn ∝ Tz/Z (looming — движение вдоль оптической оси).
                xn = (p0[:, 0] - self.cx) / self.fx
                yn = (p0[:, 1] - self.cy) / self.fy
                M = np.column_stack([np.ones_like(xn), xn, yn])
                cu, *_ = np.linalg.lstsq(M, tr[:, 0], rcond=None)
                cv, *_ = np.linalg.lstsq(M, tr[:, 1], rcond=None)
                divergence = float(cu[1] + cv[2])
                # --- ОПОРНЫЙ КАНАЛ: подобие опорный→текущий (СМЕЩЕНИЕ, не скорость) ---
                sim = self._similarity()
                kf_dx, kf_dy, kf_logs, kf_rot = (0.0, 0.0, 0.0, 0.0)
                kf_ok = sim is not None
                if sim is not None:
                    kf_dx, kf_dy, s_kf, kf_rot = sim
                    kf_logs_raw = float(math.log(s_kf)) if s_kf > 1e-6 else 0.0
                    # вычитаем вклад собственного наклона — остаётся перемещение
                    kf_logs = kf_logs_raw - self.kf_tilt_k * self._tilt_term(pitch)
                    if frozen:
                        # Кадру не верим И НИЧЕГО НЕ МЕНЯЕМ: ни отбраковку, ни
                        # `_kf_logs_prev`, ни медианный буфер. Иначе испорченные высотой
                        # значения (а) отравят медиану на pitch_smooth_n кадров вперёд и
                        # (б) уедут в накопитель при закрытии сегмента — подъём запишется
                        # как перемещение, причём с пометкой «доверенный».
                        kf_ok = False
                        kf_logs = self._kf_logs_prev if self._kf_logs_prev is not None else 0.0
                    else:
                        if (self.kf_max_step > 0 and self._kf_logs_prev is not None
                                and abs(kf_logs - self._kf_logs_prev) > self.kf_max_step):
                            self.kf_rejects += 1
                            self._kf_reject_run += 1
                            kf_logs = self._kf_logs_prev  # выброс: держим прошлое значение
                            kf_ok = False                 # и помечаем кадр недостоверным
                        else:
                            self._kf_reject_run = 0
                        self._kf_logs_prev = kf_logs
                        # Сглаживание — тем же N, что у продольной оси. Сигнал медленный
                        # (положение), поэтому медиана почти не смазывает его, а шум режет:
                        # σ 0.0025 = 0.14 м на кадр (замер keyframe_track.py).
                        self._kf_buf.append(kf_logs)
                        if len(self._kf_buf) > self.pitch_smooth_n:
                            self._kf_buf.pop(0)
                    if self.pitch_smooth_n > 1 and self._kf_buf:
                        kf_logs = float(np.median(self._kf_buf))
                    kf_seg = kf_logs                  # смещение ВНУТРИ текущего сегмента
                    kf_logs = self.kf_acc + kf_seg    # наружу — полное от точки удержания
                self._kf_vel_update(stamp, kf_logs, kf_ok)
                out = dict(
                    lateral=lateral, lateral_raw=lateral_raw, yaw_flow=yaw_flow,
                    longitudinal=longitudinal, longitudinal_raw=longitudinal_raw,
                    divergence=divergence, n=n, dt=dt,
                    # conf считается по набору СКОРОСТИ (n из свежего детекта) — как и
                    # было исходно. Здоровье опоры отдельно, в kf_n/kf_age: мерить их
                    # одним числом нельзя, наборы живут по-разному.
                    conf=float(n) / float(self.max_feats),
                    # --- опора: положение относительно опорного кадра ---
                    kf_dx=kf_dx, kf_dy=kf_dy, kf_logs=kf_logs, kf_rot=kf_rot,
                    kf_vel=self.kf_vel,
                    kf_n=len(self.kf_ref) if self.kf_ref is not None else 0,
                    kf_age=self.kf_age, kf_reseeds=self.kf_reseeds,
                    kf_segs=self.kf_segs, kf_rejects=self.kf_rejects,
                    kf_valid=kf_ok,
                    # --- канал вида сверху: МЕТРЫ и м/с ---
                    ipm_fwd=self.ipm_fwd, ipm_lat=self.ipm_lat,
                    ipm_vfwd=self.ipm_vfwd, ipm_vlat=self.ipm_vlat,
                    ipm_ok=self.ipm_ok,
                    # --- диагностика для flow_derotation_check ---
                    resid_rms=float(np.sqrt(np.mean(np.sum(tr ** 2, axis=1)))),
                    meas_rms=float(np.sqrt(np.mean(np.sum(flow ** 2, axis=1)))),
                    omega_norm=float(np.linalg.norm(omega_imu)),
                )
        # Набор СКОРОСТИ переоткрывается каждый кадр — ему так и надо (см. выше).
        self.vel_pts = self._detect(gray, self._vel_mask(gray))
        if self.vel_pts is not None:
            self.vel_pts = self.vel_pts.reshape(-1, 2)
        # Опора пересевается ТОЛЬКО когда точек не осталось (или попросили сбросить):
        # фича живёт медиану 284 кадра = 9.4 с при 30 Гц (замер keyframe_track.py по G1),
        # и в этих кадрах лежит положение, которого нет в межкадровом сдвиге.
        # На заморозке сегмент НЕ закрывается: `_kf_logs_prev` стоит на месте, значит и
        # seg_full сработать не может (проверка избыточна, но пишем явно — читателю).
        if self._seg_t0 is None:
            self._seg_t0 = stamp
        seg_age = stamp - self._seg_t0
        # доля ПОТЕРЯННЫХ точек опоры = «насколько ушла картинка» с посева
        used = (1.0 - len(self.kf_cur) / float(self.kf_n0)
                if self.kf_cur is not None and self.kf_n0 else 0.0)
        # Основной триггер — ДОЛЯ. Порог kf_seg_max оставлен СТРАХОВКОЙ, но со своим
        # длинным полом: пока он стоял в «или» наравне с долей, он и решал — закрытие
        # срабатывало раньше, чем картинка успевала уйти, и доля не меняла ничего (31-46%
        # пути наоборот при любой доле 0.15-0.50, накопитель схлопывался в ноль).
        # Без страховки же сегмент не закроется ВОВСЕ, если точки не теряются: синтетика
        # (kf_alt_freeze_test, идеальные кадры, зум без ухода точек) закрыла ОДИН сегмент
        # за 179 кадров — накопителю нечем наполняться.
        ripe = (used >= self.kf_seg_frac
                or (self._kf_logs_prev is not None
                    and abs(self._kf_logs_prev) >= self.kf_seg_max
                    and seg_age >= self.kf_seg_cap_sec))
        seg_full = (not frozen and self._kf_logs_prev is not None
                    and ripe and seg_age >= self.kf_seg_min_sec)
        # Высота не вернулась за kf_alt_hold — это НАСТОЯЩИЙ набор, опора протухла честно.
        alt_stale = frozen and self._alt_out > self.kf_alt_hold
        if (self._kf_pending or self.kf_cur is None
                or len(self.kf_cur) < self.kf_min_pts
                or self._kf_reject_run > self.kf_reject_max
                or seg_full or alt_stale):
            if not self._kf_pending and self.kf_cur is not None:
                # Сегмент ЗАСЧИТЫВАЕТСЯ ВСЕГДА. `_kf_logs_prev` — это последнее
                # ДОСТОВЕРНОЕ значение при любом поводе закрытия: на отбраковке канал
                # держит прошлое (см. ветку kf_max_step выше), на уходе высоты — тоже
                # (заморозка), при потере точек и плановом закрытии оно свежее. Выбрасывать
                # тут нечего, а выброс стоит дорого: гибнет ВСЁ накопленное смещение.
                # Замер E6f1 (уход 38 м, сигнал при этом безупречен — 8 сегментов из 8 с
                # верным знаком): контур верно затормозил на 6.7 м (+110 PWM), затем между
                # 5-й и 8-й секундой серия отбраковок выбросила сегмент, накопитель
                # схлопнулся в ноль, выход обнулился — и борт свободно разогнался с 8 до
                # 14 м. Когда сигнал отрос до +0.21, потолок 150 PWM уже не догонял.
                if self._kf_logs_prev is not None:
                    self.kf_acc += self._kf_logs_prev
                    self.kf_segs += 1
                # Счётчик оставлен ДИАГНОСТИКОЙ и сменил смысл: раньше «сегмент выброшен»,
                # теперь «закрытие по плохому поводу» (серия отбраковок). Значение при нём
                # засчитано; растущий счётчик означает, что подобие часто срывается.
                if not (seg_full or alt_stale or len(self.kf_cur) < self.kf_min_pts):
                    self.kf_reseeds += 1
            self._alt_out = 0.0             # повод отработан — счётчик заново
            self._seg_t0 = stamp            # срок сегмента отсчитывается от посева
            if self._seed(gray):
                self._kf_pitch0 = pitch     # наклон опоры — от него считаем поправку
                if alt is not None and alt > 0.2:
                    self._kf_alt0 = alt     # высота опоры — от неё считаем протухание
        self.prev_gray = gray
        self.prev_stamp = stamp
        return out
