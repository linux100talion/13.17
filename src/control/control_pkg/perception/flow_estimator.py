        #   доля 0.50             0%     22%   (но на E3f1 закрылся ОДИН сегмент — нечему копиться)
        # Доля выигрывает на обоих. Величина хода при этом всё ещё небезупречна: крутизна
        # накопителя 0.0035 и 0.0155 log/м (паспорт 0.0121), то есть верен ЗНАК, а не цена
        # метра — но именно неверный знак и разгонял борт.
        # Та же величина отвечает и на вопрос «далеко ли мы от дома» (см. home_overlap.py):
        # при уходе на десятки метров меняется НАБОР видимых объектов, а не их масштаб.
        self.kf_seg_frac = float(kf_seg_frac)
        # Пол для СТРАХОВОЧНОГО закрытия по порогу масштаба (см. ripe в process). Ставится
