# -*- coding: utf-8 -*-
"""IpmChannel — КАНАЛ ВИДА СВЕРХУ (IPM): метрические путь и скорость по полосе земли.

Миксин FlowEstimator (выделен из flow_estimator.py 2026-09-01): всё состояние живёт
на self, имена атрибутов/методов не менялись — офлайн-стенды, зовущие `_ipm_update`/
`_ipm_px`/`_wz_debias` напрямую, работают как раньше. Здесь: проекция земли в кадр
(_ipm_px, модели legacy/rsign/exact), адаптивная и масштабно-инвариантная полоса,
выпрямление (_ipm_rectify), шаг канала (_ipm_update: LK по варпу, вычитание
разворота, путь/скорость/шум), комплементарный фильтр скорости (_vel_predict) и
ФВЧ-дебиасы ω_z (_wz_debias) и прогноза ускорения (_acc_debias).

⚠️ cv2 берётся из ЭТОГО модуля: стенд ipm_band_ab подменяет `ipm.cv2` прокси для
перехвата LK — патчить надо здесь, не в flow_estimator.
"""

import math

import numpy as np

try:
    import cv2
except ImportError:
    cv2 = None


class IpmChannel:
    """Смесь (mixin): конфиг/состояние заводит _init_ipm, зовётся из FlowEstimator."""

    _VEL_HOLD = 1.0     # сек: сколько мостим провал измерений чистым прогнозом
    _ALT_GROUND = 0.08  # м: гейт «точно на земле» при включённом ipm_alt_floor.
                        # Судится по EKF-z: на земле он стоит около нуля (±0.03),
                        # а В ВОЗДУХЕ занижает на ~0.3 (вертикаль VINS) — при 0.15
                        # гейт резал истинные <0.45 м (прогон lv2 214015: код 1 в
                        # 77% тиков бина 0.15–0.5 истинных). 0.08 сжимает слепую
                        # зону до ~0.38, оставаясь выше наземного шума.
                        # (по СЫРОЙ высоте; тут же сброс фильтра скорости)

    def _init_ipm(self, ipm, ipm_x0, ipm_x1, ipm_yhalf, ipm_res, ipm_win,
                  ipm_model, ipm_derot, ipm_wz_tau, ipm_adapt, ipm_vel_tau,
                  ipm_alt_floor, ipm_scale_ref, ipm_acc_tau, ipm_wz_gate):
        # --- КАНАЛ ВИДА СВЕРХУ (IPM): МЕТРИЧЕСКОЕ смещение и скорость ---
        # Масштабный канал (kf_logs) меряет log(масштаб) созвездия, и цена метра у него
        # плавает в 14 раз: глубина точек не контролируется, точка на земле в 5 м даёт
        # при ходе 0.25 м целых 0.05 log, точка у горизонта в 50 м — 0.005.
        # Здесь полоса ЗЕМЛИ перед бортом выпрямляется в вид сверху по высоте и углам,
        # и продольный ход становится равномерным сдвигом с ИЗВЕСТНОЙ ценой пикселя.
        # Замер (ipm_flow_test.py, три бэга с кадрами), путь против истины:
        #                продольная             боковая
        #   E5f1         +1.00  corr +0.99      +0.91  corr +0.64
        #   E6f1         +1.03  corr +1.00      +1.06  corr +0.96
        #   E7f1         +0.97  corr +1.00      +1.09  corr +0.81
        # То есть метры меряются метрами, без калибровки — из одной высоты.
        # Скорость берётся наклоном МНК в окне ipm_win: покадровая производная непригодна
        # (пиксель при 0.02 м/пкс и 30 Гц = 0.6 м/с), а на окне 0.5 с выходит крутизна
        # 0.91-0.94 при corr 0.76-0.84 и ошибке 0.65-0.82 м/с (истинная СКО ~1.0).
        self.ipm = bool(ipm)
        self.ipm_x0, self.ipm_x1 = float(ipm_x0), float(ipm_x1)
        self.ipm_yhalf, self.ipm_res = float(ipm_yhalf), float(ipm_res)
        self.ipm_win = float(ipm_win)
        # Модель проекции земли в кадр: 'legacy' | 'rsign' | 'exact' (см. `_ipm_px`).
        # ⚠️ Дефолт КЛАССА — `legacy`, лётный дефолт — `exact` (config.ipm_model, серия
        # J2s). Класс намеренно оставлен на прежней модели: по ней отлетаны серии E8-H2,
        # и офлайн-инструменты, зовущие FlowEstimator напрямую, должны воспроизводить
        # те прогоны, а не молча пересчитывать их новой геометрией.
        self.ipm_model = str(ipm_model)
        # Вычитать ли предсказанное по гироскопу вращательное поле: 0 = нет, ±1 = знак.
        self.ipm_derot = float(ipm_derot)
        # --- АДАПТИВНАЯ ПОЛОСА: отодвигать окно до границы видимости ---
        # У статичной полосы x0..x1 есть ПОТОЛОК ВЫСОТЫ: нижний край кадра смотрит
        # вниз под cam_tilt + atan(cy/fy) ≈ 0.77 рад, земля на дистанции X видна лишь
        # при atan(h/X) ≤ этого угла, и при h > x1·tan(0.77) ≈ 5.85 м (на sim-оптике)
        # полоса ЦЕЛИКОМ уходит под кадр. Полёт 2026-08-18: провал ipm_ok длиной
        # 63.7 с — набор на 10 м, потом зависание на 6.0 м (15 см выше потолка!);
        # канал ожил только на 5.2 м в LAND. Демпферы крена/тангажа при этом слепы,
        # и стики пилота на этих осях мертвы.
        # ipm_adapt > 0: начало окна = max(x0, adapt·граница), ДЛИНА окна не меняется
        # (форма выпрямленного кадра постоянна — prev/rect совместимы). Сдвиг окна
        # между кадрами известен точно и вычитается из продольного накопителя.
        # 0 = выкл; класс-дефолт 0 нарочно (офлайн-инструменты воспроизводят старые
        # прогоны, тот же принцип, что у ipm_model). Лётный дефолт — config.ipm_adapt.
        self.ipm_adapt = float(ipm_adapt)
        self._ipm_prev_geo = None   # геометрия окна ПРОШЛОГО кадра (x0, длина,
                                    # yhalf, res) — дельта сдвига + декод сетки
                                    # p0 в дероте; живёт строго парой с _ipm_prev
        # --- КОМПЛЕМЕНТАРНЫЙ ФИЛЬТР СКОРОСТИ (наклон тяги + коррекция МНК-наклоном) ---
        # Чем болеет чистый МНК-наклон (замеры полётов 2026-08-18): лаг ~ipm_win/2
        # (0.25 с — на нём kp=100 звенит), провал кадров = слепота (демпфер получает
        # протухший сигнал), на скорости занижение в 2-4 раза. Физика даёт прогноз
        # ДАРОМ: горизонтальное ускорение коптера ≈ наклон вектора тяги (g·sin θ), а
        # наклон уже приходит в _ipm_update. Прогноз тикает КАЖДЫЙ кадр (в т.ч.
        # бракованный — провалы мостятся), МНК-наклон корректирует к себе с
        # постоянной времени ipm_vel_tau. Смещение прогноза от ошибки горизонта EKF
        # (A4: 2-5° → 0.3-0.9 м/с²) за окно провала ≤1 с даёт ≤0.9 м/с — терпимо,
        # дольше _VEL_HOLD без измерений фильтр признаётся слепым (ipm_ok=False).
        # ⚠️ С ФИЛЬТРОМ МЕНЯЕТСЯ СЕМАНТИКА ipm_ok: не «этот кадр посчитан», а
        # «скорости можно верить» (измерения не старше _VEL_HOLD) — демпферы больше
        # не глохнут на каждом браке кадра.
        # 0 = выкл (класс- и лётный дефолт до полётной валидации знаков наклона:
        # «конвенцию углов проверять ЧИСЛЕННО, до правки» — см. _ipm_px).
        self.ipm_vel_tau = float(ipm_vel_tau)
        # --- ПОЛ ВЫСОТЫ ПЕРЦЕПЦИИ (у земли высоте верить нельзя) ---
        # EKF-z у земли занижает на 0.25-0.3 м ВЕСЬ полёт (VINS-вертикаль;
        # прогоны LV2/1 174603 и 210917) → гейт alt<0.5 держал канал до
        # ИСТИННЫХ ~0.9 м на взлёте: демпфер слеп ровно в своей зоне
        # ответственности. ipm_alt_floor > 0: высота геометрии = max(alt,
        # floor), а гейт «на земле» опускается до _ALT_GROUND по СЫРОЙ
        # высоте. Цена: ниже floor скорость завышается в floor/h_ист раз
        # (×2.5 на истинных 0.2 м — перегейн вместо нынешней слепоты);
        # выше floor поведение не меняется вовсе. Именно ПОЛ, а не ступенька
        # «<1 м → 0.5»: у ступеньки разрыв масштаба ×2 на границе, окно МНК
        # мешает кадры двух масштабов → фантомный рывок скорости на каждом
        # пересечении. 0 = выкл (класс-дефолт: офлайн-репро старых прогонов);
        # лётный дефолт — config.ipm_alt_floor.
        self.ipm_alt_floor = float(ipm_alt_floor)
        # --- МАСШТАБНО-ИНВАРИАНТНАЯ ПОЛОСА (углы взгляда не зависят от высоты) ---
        # У ФИКСИРОВАННОЙ полосы 3-6 м есть и ПОЛ ВЫСОТЫ, не только потолок: с 0.6 м
        # она видна под скользящими 6-11°, текстура после выпрямления — каша, медиана
        # LK тянется к НУЛЮ при живом канале (прогоны lv2 040737/041255: gain к истине
        # 0.91 на 1.8-3.5 м → 0.53-0.78 на 0.4-0.8 → ~0 в худших местах; 18% годных
        # движущихся кадров видят |v|<0.15 при истинных >0.5). Демпфер при этом давит
        # в упор по полуслепому сигналу — bang-bang, борт не слушается стиков.
        # ipm_scale_ref = h_ref (м): вся геометрия полосы масштабируется s = h/h_ref —
        # x0·s, длина·s, yhalf·s, res·s. Углы взгляда при этом КОНСТАНТНЫ (на дефолтах
        # ~27-45° после adapt), пиксельный размер варпа не меняется вовсе (res ∝
        # размерам), decimation-отношение кадр→варп тоже — на ЛЮБОЙ высоте канал
        # видит ту же картинку, что сегодня на h_ref. При h = h_ref поведение
        # тождественно выключенному (s=1, бит-в-бит). Пол ipm_alt_floor применяется
        # ДО масштаба — у земли полоса не сжимается ниже floor·(x0..x1)/h_ref.
        # 0 = выкл (класс-дефолт: офлайн-репро); лётный дефолт — config.ipm_scale_ref.
        self.ipm_scale_ref = float(ipm_scale_ref)
        self._ipm_v = [0.0, 0.0]     # [vfwd, vlat(влево+)] — состояние фильтра
        self._ipm_v_t = None
        self._ipm_meas_t = -1e9      # время последнего ГОДНОГО кадра (свежесть)
        # --- СНЯТИЕ ПОСТОЯННОЙ СОСТАВЛЯЮЩЕЙ ω_z (ФВЧ), сек; 0 = не снимать ---
        # Гироскоп даёт ω_z со СМЕЩЕНИЕМ НУЛЯ: замер против одометрии, рад/с — I1s1 −0.0236,
        # J2s1 −0.0060, L2s1 −0.0282, L2s2 −0.0242. Пока зрение гироскоп не использовало,
        # это никого не трогало; вычитание разворота (ipm_derot) умножает смещение на плечо
        # полосы 4.5 м и вливает −0.03…−0.13 м/с прямо в измерение боковой скорости. Демпфер
        # СКОРОСТИ зануляет то, что видит → борт едет ровно с этой скоростью (серия L2s: вбок
        # −4.78 ± 4.48 м, все пять прогонов в одну сторону).
        # Поэтому из ω_z вычитается собственное скользящее среднее с постоянной времени
        # ipm_wz_tau: остаётся только ПЕРЕМЕННАЯ часть разворота, ради которой поправка и
        # вводилась. Законно потому, что курс УДЕРЖИВАЕТСЯ (DpYawHold) — истинная средняя
        # скорость разворота за десятки секунд равна нулю, и всё, что среднее видит на таком
        # окне, есть смещение датчика. ⚠️ На манёвре с ПОСТОЯННЫМ разворотом (облёт по кругу)
        # среднее съело бы и сам сигнал — там ручку надо выключать.
        # Смещение своё у каждого прогона (и, вероятно, у каждого включения), поэтому оно
        # ОЦЕНИВАЕТСЯ на ходу, а не вбивается константой.
        self.ipm_wz_tau = float(ipm_wz_tau)
        # ipm_wz_gate (рад/с): оценку НУЛЯ ω_z двигать только пока борт НЕ разворачивается
        # (|ω_z − оценка| < gate). Без гейта ФВЧ с τ=2 с за разворот принимает сам
        # разворот за смещение: полёт ab_frame (5 м/с, рама станции) — за развороты
        # 70…335° при 40…60 °/с канал наматывает ФАНТОМНЫЙ боковой путь +0.9…+4.8 м
        # (∫(канал − гейн·истина)dt), демпфер гонит борт по фантому, а рама станции
        # уносит гвоздь — снос 2–4 м за 5 с после каждого разворота. С гейтом оценка
        # замерзает на развороте и продолжает в висении, где ω_z ≈ 0 (FCU держит
        # курс) и смещение видно чище всего. 0 = без гейта (прежнее правило).
        self.ipm_wz_gate = float(ipm_wz_gate)
        self._wz_bias = None
        self._wz_t = None
        self._wz_n = 0
        # --- СНЯТИЕ ПОСТОЯННОЙ СОСТАВЛЯЮЩЕЙ ПРОГНОЗА УСКОРЕНИЯ (ФВЧ), сек; 0 = не снимать ---
        # ТА ЖЕ БОЛЕЗНЬ, ЧТО У ω_z ВЫШЕ, другой источник. `_vel_predict` считает ускорение
        # по НАКЛОНУ ТЯГИ (a = g·sin θ) — это верно в свободном полёте, но в УДЕРЖАНИИ
        # ПРОТИВ ВЕТРА наклон уравновешен сопротивлением, и истинное ускорение НОЛЬ при
        # ненулевом наклоне. Комплементарный фильтр интегрирует прогноз и подтягивается к
        # МНК-наклону с постоянной ipm_vel_tau, поэтому остаётся установившаяся ошибка
        # ≈ g·sin(крен)·ipm_vel_tau. Замер по прогону 194912 (висение на 0.26 м, ветер
        # 5 м/с, борт держит крен +3.92°±1.42°): смещение боковой оси −0.25 м/с при
        # vel_tau 0.4, −0.12 при 0.2, −0.00 при 0 — ЛИНЕЙНО по τ, как и предсказывает
        # формула (9.81·sin(3.92°)·0.4 = 0.27). corr(остаток, крен) = +0.93 при
        # corr(крен, истинная боковая) = −0.21, то есть это не путаница причины со
        # следствием. Дальше как обычно: демпфер зануляет то, что ВИДИТ → борт едет
        # ровно с этой скоростью (истинный остаточный снос того полёта +0.19 м/с влево).
        # Лечение — вычесть из прогноза его же скользящее среднее: остаётся ПЕРЕМЕННАЯ
        # часть (манёвр), ради которой прогноз и вводился, а балансирующий ветер наклон
        # уходит. Законно по тому же рассуждению, что у ω_z: истинное СРЕДНЕЕ ускорение за
        # десятки секунд удержания равно нулю (иначе скорость росла бы неограниченно).
        # ⚠️ На ДЛИТЕЛЬНОМ настоящем разгоне среднее съело бы и сигнал — там ручку выключать.
        self.ipm_acc_tau = float(ipm_acc_tau)
        self._acc_bias = None        # [af, al] — медленное среднее прогноза
        self._acc_t = None
        self._acc_n = 0
        self._ipm_prev = None
        self._ipm_prev_t = None
        self._ipm_hist = []          # (t, путь вперёд, путь вбок) — окно для скорости
        self.ipm_fwd = self.ipm_lat = 0.0
        self.ipm_vfwd = self.ipm_vlat = 0.0
        # ШУМ КАНАЛА онлайн, м/кадр (≈0.8σ покадрового шума пути) — считается у
        # приращения пути ниже; растёт с тайминг-ошибкой углов ∝ высоте (замер
        # lv2_joy_20260829_182126: 14 → 95 мм на 0.3 → 8.3 м; ab_soft: 231 мм на 17.5).
        self.ipm_noise_fwd = self.ipm_noise_lat = 0.0
        self.ipm_ok = False
        # ПРИЧИНА, почему ЭТОТ кадр не дал измерения (0 = дал). Мотив: разбор
        # LV2/1 (2026-08-25) упёрся в бинарный ipm_ok — 31% слепоты канала на
        # 1.1 м с неразличимыми причинами (какой из ранних return бьёт — из
        # bag не восстановить). Коды:
        #   0 кадр посчитан        4 мало фич (<20 в опорном кадре;
        #   1 гейт высоты            сюда же полоса под нижним краем
        #     (alt None / <0.5)      кадра — варп там чёрный)
        #   2 окно не видно        5 мало выживших LK (<15)
        #     (взгляд у горизонта) 6 канал выключен (ipm=False)
        #   3 варп за кадром       7 нет опорного кадра (первый после
        #     (точка за камерой /    сброса или смена размера сетки —
        #      полоса далеко вбок)   хвост любого сброса 1-3)
        # Семантика ПОКАДРОВАЯ и от ipm_vel_tau не зависит: фильтр может
        # держать ipm_ok=True на браке кадра — ipm_fail и тогда говорит, чем
        # кадр плох. Кодировка в /flow_dbg8.z — см. ros_io.publish_axes.
        self.ipm_fail = 7

    def _ipm_px(self, X, Y, h, pitch, roll):
        """Точка земли (X вперёд, Y вправо, глубина h) → пиксель кадра. None вне кадра.

        Оси камеры: x вправо, y вниз, z вперёд. Модель выбирается `ipm_model`.

        ⚠️ УГЛЫ ПРИХОДЯТ В СИСТЕМЕ ROS (ENU/FLU: y ВЛЕВО, z ВВЕРХ), а не в авиационной
        FRD. По правилу правой руки вокруг оси «влево» вектор вперёд уходит ВНИЗ, то есть
        ПОЛОЖИТЕЛЬНЫЙ ТАНГАЖ ЗДЕСЬ = НОС ВНИЗ. Поэтому `cam_tilt + pitch` ВЕРНО: нос вниз
        увеличивает угол взгляда вниз. Это проверено замером, а не рассуждением: попытка
        «исправить» знак на `cam_tilt − pitch` разнесла продольный масштаб с 1.10 до 4.06
        при ошибке 2.64 м/с вместо 0.40 (стенд `att_extrap_test.py`, бэг I1s1).
        Ошибка вывода была в том, что эталонная цепочка выводилась в FRD, где знак
        обратный. Не повторять: конвенцию углов проверять ЧИСЛЕННО, до правки.

        `legacy` — лётная модель, на ней отлетаны серии E8-H2: наклон `cam_tilt + pitch`
        вокруг оси x, затем крен вокруг ОПТИЧЕСКОЙ оси.
        `rsign`  — то же, но крен на −φ. Изолирует ЗНАК КРЕНА: тангаж не трогает.
        `exact`  — честная цепочка: точка (X вперёд, Y вправо, h вниз) → корпус
                   `Rx(φ)·Ry(−θ)` (минус — перевод тангажа ROS→FRD) → камера матрицей
                   крепления `M(cam_tilt)`. Отличается от `legacy` тем, что крен идёт
                   вокруг ПРОДОЛЬНОЙ оси корпуса, наклонённой к оптической на `cam_tilt`,
                   а не вокруг самой оптической.

        ⚠️ `cam_tilt + pitch` живёт ещё в двух местах (наклонная поправка опоры и строка
        горизонта для подгонки курса). Там знак НЕ трогали: это отдельные каналы, и
        менять их надо своим замером, а не заодно."""
        if self.ipm_model == 'exact':
            cr, sr = math.cos(roll), math.sin(roll)
            cp, sp = math.cos(-pitch), math.sin(-pitch)
            ct, stl = math.cos(self.cam_tilt), math.sin(self.cam_tilt)
            Rx = np.array([[1.0, 0.0, 0.0], [0.0, cr, sr], [0.0, -sr, cr]])
            Ry = np.array([[cp, 0.0, -sp], [0.0, 1.0, 0.0], [sp, 0.0, cp]])
            M = np.array([[0.0, 1.0, 0.0], [-stl, 0.0, ct], [ct, 0.0, stl]])
            P = M @ (Rx @ (Ry @ np.array([X, Y, h], dtype=np.float64)))
        else:
            rs = -1.0 if self.ipm_model == 'rsign' else +1.0
            a_down = self.cam_tilt + pitch
            ca, sa = math.cos(a_down), math.sin(a_down)
            cr, sr = math.cos(rs * roll), math.sin(rs * roll)
            P = np.array([[cr, -sr, 0.0], [sr, cr, 0.0], [0.0, 0.0, 1.0]]) @ (
                np.array([[1.0, 0.0, 0.0], [0.0, ca, -sa], [0.0, sa, ca]])
                @ np.array([Y, h, X], dtype=np.float64))
        if P[2] <= 0.05:
            return None
        return [self.cx + self.fx * P[0] / P[2], self.cy + self.fy * P[1] / P[2]]

    def _vel_reset(self):
        """Скорость с фильтром — только в воздухе: на земле/без баро состояние 0."""
        self._ipm_v = [0.0, 0.0]
        self._ipm_v_t = None
        self._ipm_meas_t = -1e9

    def _acc_debias(self, stamp, af, al):
        """Прогноз ускорения без постоянной составляющей (ФВЧ, τ = ipm_acc_tau).

        Один в один `_wz_debias` (включая разгон веса max(1−e^(−dt/τ), 1/n): чистое
        экспоненциальное сглаживание тащило бы ошибку первого отсчёта τ секунд).
        0 = отдать прогноз как есть — прежнее поведение бит-в-бит."""
        if self.ipm_acc_tau <= 0.0:
            return af, al
        if self._acc_bias is None:
            self._acc_bias = [af, al]
            self._acc_t = stamp
            self._acc_n = 1
            return 0.0, 0.0
        dt = stamp - self._acc_t
        self._acc_t = stamp
        self._acc_n += 1
        if dt > 0.0:
            a = max(1.0 - math.exp(-dt / self.ipm_acc_tau), 1.0 / self._acc_n)
            self._acc_bias[0] += a * (af - self._acc_bias[0])
            self._acc_bias[1] += a * (al - self._acc_bias[1])
        return af - self._acc_bias[0], al - self._acc_bias[1]

    def _vel_predict(self, stamp, pitch, roll, wz):
        """Прогноз скорости на кадр: наклон тяги + поворот body-осей рысканием.

        Знаки — в конвенции канала (см. _ipm_px): pitch>0 = нос ВНИЗ → разгон
        вперёд (+vfwd); roll>0 = правое крыло вниз → разгон вправо, а vlat у нас
        ЛЕВО-положителен → минус. wz>0 = разворот влево: продольная и боковая
        компоненты скорости перетекают друг в друга (−ω×v).
        ⚠️ Оба знака наклона подлежат ЧИСЛЕННОЙ полётной проверке до включения
        лётного дефолта — печальный опыт выведенных знаков задокументирован
        в _ipm_px."""
        if self._ipm_v_t is None:
            self._ipm_v_t = stamp
            return
        dt = min(max(stamp - self._ipm_v_t, 0.0), 0.2)
        self._ipm_v_t = stamp
        vf, vl = self._ipm_v
        af = 9.81 * math.sin(pitch)
        al = -9.81 * math.sin(roll)
        af, al = self._acc_debias(stamp, af, al)   # снять балансирующий ветер наклон
        self._ipm_v[0] = vf + (af + wz * vl) * dt
        self._ipm_v[1] = vl + (al - wz * vf) * dt
        if stamp - self._ipm_meas_t <= self._VEL_HOLD:
            self.ipm_vfwd, self.ipm_vlat = self._ipm_v

    def _ipm_window(self, h, pitch, x0=None):
        """Начало полосы ЭТОГО кадра: базовое x0 или отодвинутое до границы видимости.

        Граница: земля на дистанции X видна, пока atan(h/X) не глубже нижнего края
        кадра a = cam_tilt + pitch + atan(cy/fy). pitch — в конвенции канала (ROS,
        положительный = нос ВНИЗ, как в `_ipm_px` legacy), то есть клевок опускает
        границу ближе, задирание носа — отодвигает. Запас ipm_adapt (≈1.05) держит
        ближний край окна чуть дальше границы: на самой кромке фичи полугаснут.
        None = полосы не видно вовсе (взгляд у горизонта).
        x0 — базовое начало этого кадра (масштабно-инвариантная полоса даёт своё;
        None = ipm_x0)."""
        if x0 is None:
            x0 = self.ipm_x0
        if self.ipm_adapt <= 0.0:
            return x0
        a = self.cam_tilt + pitch + math.atan2(self.cy, self.fy)
        if a >= 0.5 * math.pi:          # смотрим отвесно вниз — видно всё
            return x0
        if a <= 0.05:                   # нос задран к горизонту — полосы нет
            return None
        return max(x0, self.ipm_adapt * h / math.tan(a))

    def _ipm_rectify(self, gray, h, pitch, roll, x0=None, x1=None,
                     yhalf=None, res=None, dims=None):
        """Полоса земли → метрический вид сверху (1 пиксель = res метров).
        x0/x1/yhalf/res — геометрия этого кадра (None = базовая, для
        офлайн-инструментов; масштабно-инвариантная полоса даёт свою).
        dims — пиксельный размер варпа (w, hh); None = посчитать делением здесь.
        _ipm_update передаёт размер, посчитанный ОТ БАЗОВОЙ геометрии: отношение
        размер/res математически не зависит от масштаба s, но деление уже
        масштабированных float даёт ±1 пиксель (199.99↔200.01) — и смена формы
        варпа на ходе высоты рвала бы канал кодом 7."""
        if x0 is None:
            x0 = self.ipm_x0
        if x1 is None:
            x1 = self.ipm_x1
        if yhalf is None:
            yhalf = self.ipm_yhalf
        if res is None:
            res = self.ipm_res
        src = []
        for X, Y in ((x0, -yhalf), (x0, yhalf), (x1, yhalf), (x1, -yhalf)):
            p = self._ipm_px(X, Y, h, pitch, roll)
            if p is None:
                return None
            src.append(p)
        src = np.array(src, dtype=np.float32)
        if src[:, 0].min() < -2 * self.cx or src[:, 0].max() > 4 * self.cx:
            return None                     # полоса ушла далеко за кадр — доверять нечему
        if dims is None:
            dims = (max(8, int(2 * yhalf / res)), max(8, int((x1 - x0) / res)))
        w, hh = dims
        dst = np.array([[0, hh - 1], [w - 1, hh - 1], [w - 1, 0], [0, 0]], dtype=np.float32)
        return cv2.warpPerspective(gray, cv2.getPerspectiveTransform(src, dst), (w, hh))

    def _wz_debias(self, stamp, wz):
        """ω_z без постоянной составляющей (ФВЧ первого порядка, τ = ipm_wz_tau).

        Оценка смещения ведётся ВСЕГДА, пока идут кадры, — в том числе на земле и на
        подъёме, где борт ещё не разворачивается и среднее чище всего. Ручка 0 отдаёт ω_z
        как есть (прежнее поведение)."""
        wz = float(wz)
        if self.ipm_wz_tau <= 0.0:
            return wz
        if self._wz_bias is None:
            self._wz_bias = wz          # старт с первого отсчёта, а не с нуля: иначе первые
            self._wz_t = stamp          # τ секунд поправка работала бы по СЫРОМУ смещению
            self._wz_n = 1
            return 0.0
        dt = stamp - self._wz_t
        self._wz_t = stamp
        if self.ipm_wz_gate > 0.0 and abs(wz - self._wz_bias) > self.ipm_wz_gate:
            return wz - self._wz_bias   # разворот: оценку нуля не трогаем
        self._wz_n += 1
        if dt > 0.0:
            # ⚠️ РАЗГОН ОЦЕНКИ. Один отсчёт ω_z шумит на 0.13 рад/с — вшестеро больше самого
            # смещения (0.02). Чистое экспоненциальное сглаживание стартует ИМЕННО с такого
            # отсчёта и тащит его ошибку τ секунд: при τ=10 и прогреве 8 с в оценке остаётся
            # 43% начального промаха, и длинное τ выходило ХУЖЕ короткого (замер по I1s1:
            # сдвиг τ=3 −0.01, τ=5 +0.03, τ=10 +0.17 — порядок обратный физике).
            # Поэтому вес отсчёта берётся не меньше 1/n: пока набрано меньше τ/dt отсчётов,
            # это ТОЧНОЕ среднее по всему, что пришло, и лишь дальше — забывающее окно τ.
            a = max(1.0 - math.exp(-dt / self.ipm_wz_tau), 1.0 / self._wz_n)
            self._wz_bias += a * (wz - self._wz_bias)
        return wz - self._wz_bias

    def _ipm_update(self, gray, stamp, alt, pitch, roll, wz=0.0):
        """Шаг канала вида сверху: путь в метрах + скорость наклоном МНК в окне."""
        wz = self._wz_debias(stamp, wz)
        self.ipm_ok = False
        # Гейт высоты: с полом (ipm_alt_floor) — только «точно на земле»
        # (_ALT_GROUND по сырой высоте), без пола — прежние 0.5.
        gate = self._ALT_GROUND if self.ipm_alt_floor > 0.0 else 0.5
        if not self.ipm or alt is None or alt < gate:
            self.ipm_fail = 6 if not self.ipm else 1
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_geo = None
            self._vel_reset()
            return
        if self.ipm_alt_floor > 0.0:
            alt = max(alt, self.ipm_alt_floor)   # геометрия — не ниже пола
        if self.ipm_vel_tau > 0.0:
            # прогноз тикает на КАЖДОМ кадре, включая бракованные — провалы мостятся;
            # ipm_ok при фильтре = «скорости можно верить» (измерения свежее _VEL_HOLD)
            self._vel_predict(stamp, pitch, roll, wz)
            self.ipm_ok = (stamp - self._ipm_meas_t) <= self._VEL_HOLD
        # Геометрия полосы ЭТОГО кадра. При ipm_scale_ref всё ∝ s = alt/h_ref
        # (углы взгляда константны, см. ctor); res ∝ s держит пиксельный размер
        # варпа НЕИЗМЕННЫМ — prev/rect совместимы на любом ходе высоты, а смена
        # масштаба между соседними кадрами (плавная, 30 fps) читается LK как
        # лёгкий зум с медианой ~0.
        sc = alt / self.ipm_scale_ref if self.ipm_scale_ref > 0.0 else 1.0
        length = (self.ipm_x1 - self.ipm_x0) * sc
        yhalf = self.ipm_yhalf * sc
        res = self.ipm_res * sc
        x0 = self._ipm_window(alt, pitch, self.ipm_x0 * sc)
        if x0 is None:
            self.ipm_fail = 2
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_geo = None
            return
        x1 = x0 + length
        # размер варпа — от БАЗОВОЙ геометрии (инвариантен к s, см. _ipm_rectify);
        # при s=1 деление тождественно прежнему — бит-в-бит с легаси
        dims = (max(8, int(2 * self.ipm_yhalf / self.ipm_res)),
                max(8, int((self.ipm_x1 - self.ipm_x0) / self.ipm_res)))
        rect = self._ipm_rectify(gray, alt, pitch, roll, x0, x1, yhalf, res, dims)
        if rect is None:
            self.ipm_fail = 3
            self._ipm_prev = None
            self._ipm_prev_t = None
            self._ipm_prev_geo = None
            return
        prev = self._ipm_prev
        prev_t = self._ipm_prev_t
        prev_geo = self._ipm_prev_geo
        # ⚠️ ВРЕМЯ ОПОРНОГО КАДРА ОБНОВЛЯЕТСЯ ЗДЕСЬ ЖЕ, вместе с самим кадром. Раньше оно
        # ставилось в конце, после успешного шага потока, и три ранних `return` ниже (мало
        # точек, мало выживших, смена размера) сдвигали КАДР, но не ВРЕМЯ. Тогда `dpsi`
        # считался по интервалу в несколько кадров вместо одного и вычитал разворот кратно
        # сильнее нужного. Офлайн на спокойном бэге срывов почти нет — стенд это пропустил;
        # в полёте на трясущемся борту канал уходил вразнос (серия K2s: продольная СКО
        # 2.06-2.44 м/с в трёх прогонах из пяти против 0.11-0.23 в остальных).
        self._ipm_prev = rect
        self._ipm_prev_t = stamp
        self._ipm_prev_geo = (x0, length, yhalf, res)
        if prev is None or prev.shape != rect.shape:
            self.ipm_fail = 7
            return
        pts = self._detect(prev)
        if pts is None or len(pts) < 20:
            self.ipm_fail = 4
            return
        pts = pts.reshape(-1, 1, 2).astype(np.float32)
        p1, st, _ = cv2.calcOpticalFlowPyrLK(prev, rect, pts, None, **self._lk)
        p0b, st2, _ = cv2.calcOpticalFlowPyrLK(rect, prev, p1, None, **self._lk)
        ok = (st.reshape(-1) == 1) & (st2.reshape(-1) == 1)
        ok &= np.linalg.norm(p0b.reshape(-1, 2) - pts.reshape(-1, 2), axis=1) < 1.0
        if ok.sum() < 15:
            self.ipm_fail = 5
            return
        p0 = pts.reshape(-1, 2)[ok]
        d = p1.reshape(-1, 2)[ok] - p0
        # --- ВЫЧИТАНИЕ РАЗВОРОТА (ipm_derot) ---
        # Медиана смещений считает поле «только сдвиг», поэтому разворот борта читается
        # как боковой снос: полоса лежит ВПЕРЕДИ, и поворот на dψ двигает её вбок на
        # X·dψ (X = 3…6 м), то есть на порядок сильнее, чем сам разворот виден в полосе.
        # Оценивать dψ ЗДЕСЬ не надо и вредно: плечо 3→6 м слабое, а гироскоп даёт ω_up
        # прямо и точно. Поэтому предсказанное вращательное поле ВЫЧИТАЕТСЯ поточечно,
        # а медиана остаётся на месте со всей своей устойчивостью к выбросам (сцена не
        # плоская: стены и здания дают параллакс, МНК бы на них поехал).
        # Геометрия: точка сетки (столбец u, строка v) ↔ земля Y = u·res − yhalf (вправо),
        # X = x1 − v·res (вперёд). Разворот влево на dψ: dX = −Y·dψ, dY = +X·dψ, значит
        # в сетке d_столбец = +X·dψ/res, d_строка = +Y·dψ/res.
        # ⚠️ ЗНАК ручкой, а не выводом. В этой кампании два знака подряд были выведены
        # неверно (крен в проекции, тангаж в ROS-конвенции), оба поймал замер. `ipm_derot`
        # = 0 (выкл) / +1 / −1, выбирается стендом att_extrap_test.py по одним кадрам.
        if self.ipm_derot and prev_t is not None:
            dpsi = self.ipm_derot * float(wz) * (stamp - prev_t)
            if abs(dpsi) > 1e-9:
                # p0 живут в сетке ПРОШЛОГО кадра → его геометрия целиком
                px0, plen, pyh, pres = prev_geo
                Yg = p0[:, 0] * pres - pyh
                Xg = (px0 + plen) - p0[:, 1] * pres
                d = d - np.column_stack([Xg * dpsi / pres, Yg * dpsi / pres])
        # столбец = Y вправо, строка = X вперёд (строка 0 — дальний край). Это оси
        # СЕТКИ, а не знака скорости борта: фичи в полосе движутся ПРОТИВ хода борта.
        # Продольная крутизна к скорости борта +1.00/+1.03/+0.97 (вперёд = плюс).
        # ⚠️ Боковая: ipm_lat/ipm_vlat ЛЕВО-положительны. Старая калибровка
        # «+0.91/+1.06/+1.09 вправо» мерялась против twist.y в предположении FRD,
        # а body-twist Gazebo — FLU (y = влево); перезамер полёта 2026-08-18 по
        # производной мировой позиции дал ipm_vlat ≈ −v_right с наклоном ~1.
        # Потребитель (DpRollRate._cmd) компенсирует минусом, как DpRollHold.
        d_lat = float(np.median(d[:, 0])) * res
        self.ipm_lat += d_lat
        # Сдвиг АДАПТИВНОГО окна между кадрами (x0 − prev_x0) неотличим для потока от
        # хода вперёд (статичная точка земли сползает вниз по сетке ровно на сдвиг),
        # но он известен ТОЧНО — вычитаем. При ipm_adapt=0 окна совпадают, дельта 0.
        d_fwd = float(np.median(d[:, 1])) * res - (x0 - prev_geo[0])
        self.ipm_fwd += d_fwd
        # ШУМ КАНАЛА онлайн: |приращение за кадр − v̂·dt| (v̂ — отфильтрованная скорость
        # ПРОШЛОГО кадра), сглажено τ=2 с; ≈0.8σ покадрового шума пути (м/кадр).
        # Проверено реплеем ab_soft/182126 против истины Gazebo: corr 0.97–0.99,
        # масштаб 0.81–0.93. Невязка МНК в окне для этого НЕ годится (случайное
        # блуждание пути в окне почти линейно — недооценка в 8×). Потребитель —
        # мягкость демпфера по измеренному шуму (_IpmGated.soft_noise).
        if prev_t is not None and stamp > prev_t:
            dtf = stamp - prev_t
            a_n = 1.0 - math.exp(-dtf / 2.0)
            self.ipm_noise_fwd += a_n * (abs(d_fwd - self._ipm_v[0] * dtf) - self.ipm_noise_fwd)
            self.ipm_noise_lat += a_n * (abs(d_lat - self._ipm_v[1] * dtf) - self.ipm_noise_lat)
        self.ipm_ok = True
        self.ipm_fail = 0
        self._ipm_meas_t = stamp
        self._ipm_hist.append((stamp, self.ipm_fwd, self.ipm_lat))
        while self._ipm_hist and stamp - self._ipm_hist[0][0] > self.ipm_win:
            self._ipm_hist.pop(0)
        if len(self._ipm_hist) >= 4:
            a = np.array(self._ipm_hist)
            tc = a[:, 0] - a[:, 0].mean()
            den = float(np.dot(tc, tc))
            if den > 0 and a[-1, 0] - a[0, 0] > 0.5 * self.ipm_win:
                sf = float(np.dot(tc, a[:, 1] - a[:, 1].mean()) / den)
                sl = float(np.dot(tc, a[:, 2] - a[:, 2].mean()) / den)
                if self.ipm_vel_tau > 0.0:
                    # комплементарная коррекция прогноза к МНК-наклону: быстрые
                    # движения несёт прогноз (без лага), постоянную составляющую —
                    # измерение (без дрейфа наклонного смещения EKF)
                    k = (min(1.0, max(0.0, stamp - prev_t) / self.ipm_vel_tau)
                         if prev_t is not None else 1.0)
                    self._ipm_v[0] += k * (sf - self._ipm_v[0])
                    self._ipm_v[1] += k * (sl - self._ipm_v[1])
                    self.ipm_vfwd, self.ipm_vlat = self._ipm_v
                else:
                    self.ipm_vfwd, self.ipm_vlat = sf, sl
